"""The shipped parser, and the only way this package looks at a document.

Nothing here reads Markdown or XML. A document becomes readable exactly once, by
`vibe progress mirror` — the engine's own parse, projection dispatch and content
hashing (PROP-045 `##PROJECTION-READ`) — and every consumer downstream reads the
`ParsedDoc` JSON it wrote. A second implementation of the hash recipe is the bug
`text-stability.py`'s `#recipe-drift` guard was built to catch, and the way not
to need that guard is to have no second implementation.
"""

import collections
import json
import os
import pathlib
import shutil
import subprocess

from .refusal import Refusal

# The scope a materialised historical tree gets: both legacy roots, both live
# roots, both serialisations. Narrow by construction anyway — such a tree holds
# exactly the blobs this package put in it.
SCRATCH_SCOPE = (
    "# Generated by corpus_migration — a materialised tree's scope. Narrow by\n"
    "# construction: the tree holds exactly the files that were written into it.\n"
    "schema = 1\n"
    'include = ["spec/**/*.md", "spec/**/*.xml",\n'
    '           "packages/**/*.md", "packages/**/*.xml",\n'
    '           "vibevm/vibespecs/**/*.md", "vibevm/vibespecs/**/*.xml",\n'
    '           "vibevm/vibepacks/**/*.md", "vibevm/vibepacks/**/*.xml"]\n'
    "exclude = []\n\n"
    "[progress]\n"
    'cache_dir = ".payloads"\n'
)


class Mirror:
    """A `run/mirror/` directory as written by `vibe progress mirror`."""

    def __init__(self, directory):
        self.dir = pathlib.Path(directory)
        self._cache = {}

    def _file(self, path):
        return self.dir / (path.replace("/", "__") + ".json")

    def has(self, path):
        return self._file(path).exists()

    def doc(self, path):
        if path not in self._cache:
            f = self._file(path)
            if not f.exists():
                raise Refusal(f"no mirror for `{path}` under {self.dir}")
            self._cache[path] = json.loads(f.read_text(encoding="utf-8"))
        return self._cache[path]

    def paths(self):
        return sorted(p.name[:-len(".json")].replace("__", "/")
                      for p in self.dir.glob("*.json"))

    def marked_facts(self, path):
        """`{fact id: [content hash, …]}` — a list, so a duplicate stays visible."""
        out = collections.defaultdict(list)
        for block in self.doc(path)["blocks"]:
            for fact in block.get("facts", []):
                if fact.get("marked") and fact.get("id"):
                    out[fact["id"]].append(fact["content_hash"])
        return out

    def fact_bodies(self, path):
        """`{fact id: [body, …]}`, the same shape and for the same reason."""
        out = collections.defaultdict(list)
        for block in self.doc(path)["blocks"]:
            for fact in block.get("facts", []):
                if fact.get("marked") and fact.get("id"):
                    out[fact["id"]].append(fact["body"])
        return out

    def units(self, path):
        return self.doc(path)["units"]

    def content_hash(self, path):
        return self.doc(path)["content_hash"]


def unit_frag(unit):
    """A unit's address fragment, exactly as `progress_core::baseline::unit_addr`
    spells it: its anchor, or `L<line_start>` when it has none."""
    return unit.get("anchor") or "L%d" % unit["line_start"]


