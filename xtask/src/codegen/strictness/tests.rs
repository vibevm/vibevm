//! Unit tests for the strictness pass — one per behaviour the pass
//! owes the registry and the driver: the stamping itself (every
//! struct, no enum), the byte-for-byte pass-through of every other
//! role, the named skip of a record whose schema no phase has built
//! yet, the silence around legal duplicates and schema-less records,
//! and the loud refusals — two roles on one schema, a schema no
//! record claims, a struct the pinned emission shape cannot explain.
//! The registry samples are written to a scratch root and read through
//! the real loader: the pass exists to be exact about the registry, so
//! the tests must read the registry, not a hand-built imitation of it.

use anyhow::{Context, Result};
use tempfile::TempDir;

use super::{Strictness, apply_strictness};

/// A generated file in the shape of the real ones — two structs, a
/// vocabulary enum, a tagged union — quoted after the pinned emission
/// of jtd-codegen 0.4.1. Under a `none` role exactly the two structs
/// take the attribute; the enums never do.
const WHOLE_FILE: &str = r#"// Code generated by jtd-codegen for Rust v0.2.1

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

#[derive(Serialize, Deserialize)]
pub struct Config {
    #[serde(rename = "name")]
    pub name: String,
}

#[derive(Serialize, Deserialize)]
pub enum NamingConvention {
    #[serde(rename = "fqdn")]
    Fqdn,
}

#[derive(Serialize, Deserialize)]
#[serde(tag = "kind")]
pub enum ConfigEntry {
    #[serde(rename = "directory")]
    Directory(ConfigDirectory),
}

#[derive(Serialize, Deserialize)]
pub struct ConfigDirectory {
    #[serde(rename = "entries")]
    pub entries: u32,
}
"#;

/// A scratch repo root carrying `registry` as `formats/REGISTRY.toml`
/// and an empty file at every path in `schemas`: the pass reads a
/// schema's registry record and its existence, never its content, so
/// an empty file is the honest fixture.
fn scratch_root(registry: &str, schemas: &[&str]) -> Result<TempDir> {
    let root = tempfile::tempdir().context("creating the scratch root")?;
    let formats = root.path().join("formats");
    std::fs::create_dir_all(&formats).context("creating the scratch formats dir")?;
    std::fs::write(formats.join("REGISTRY.toml"), registry)
        .context("writing the scratch registry")?;
    for rel in schemas {
        let path = root.path().join(rel);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
        }
        std::fs::write(&path, "{}\n").with_context(|| format!("writing {}", path.display()))?;
    }
    Ok(root)
}

/// One `[format.<id>]` record with every field the loader requires.
fn record(id: &str, schema: &str, foreign_parsers: &str) -> String {
    format!(
        "[format.{id}]\nepoch = 1\nschema = \"{schema}\"\nrecoverable = true\nforeign_parsers = \"{foreign_parsers}\"\n"
    )
}

/// A4.1 — a `none` role with a schema on disk stamps every struct of
/// the file and not one enum. The assert is on the exact output, not a
/// substring, so a partial or creative rewrite cannot sneak through.
#[test]
fn a_none_role_stamps_every_struct_and_no_enum() -> Result<()> {
    let root = scratch_root(
        &record("config", "schemas/config.jtd.json", "none"),
        &["schemas/config.jtd.json"],
    )?;
    let strictness = Strictness::load(root.path())?;
    let schema = root.path().join("schemas").join("config.jtd.json");
    let out = apply_strictness(WHOLE_FILE, "config/mod.rs", &schema, &strictness)?;
    assert_eq!(
        out,
        WHOLE_FILE
            .replace(
                "#[derive(Serialize, Deserialize)]\npub struct Config {",
                "#[derive(Serialize, Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct Config {",
            )
            .replace(
                "#[derive(Serialize, Deserialize)]\npub struct ConfigDirectory {",
                "#[derive(Serialize, Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct ConfigDirectory {",
            ),
        "exactly the two structs take the attribute"
    );
    Ok(())
}

/// A4.2 — two records claiming one schema with different roles refuse,
/// the message naming the schema and both records with their roles.
/// The site does not exist in today's registry; the branch exists in
/// the machine and is proven here.
#[test]
fn two_roles_on_one_schema_refuse_naming_both() -> Result<()> {
    let root = scratch_root(
        &format!(
            "{}\n{}",
            record("index-entry", "schemas/index/e1/entry.jtd.json", "many"),
            record("index-primary", "schemas/index/e1/entry.jtd.json", "none"),
        ),
        &["schemas/index/e1/entry.jtd.json"],
    )?;
    let err = Strictness::read(root.path())
        .map(|_| ())
        .expect_err("two roles on one schema have no single policy");
    let msg = err.to_string();
    assert!(
        msg.contains("schemas/index/e1/entry.jtd.json"),
        "names the schema: {msg}"
    );
    assert!(
        msg.contains("index-entry") && msg.contains("many"),
        "names the first record with its role: {msg}"
    );
    assert!(
        msg.contains("index-primary") && msg.contains("none"),
        "names the second record with its role: {msg}"
    );
    assert!(
        msg.contains("cargo xtask codegen"),
        "says what to do: {msg}"
    );
    Ok(())
}

/// A4.3 — `ours` and `many` leave the file byte for byte as it was.
#[test]
fn ours_and_many_roles_leave_the_file_byte_for_byte() -> Result<()> {
    let root = scratch_root(
        &format!(
            "{}\n{}",
            record("journal", "schemas/journal/e1/journal.jtd.json", "ours"),
            record("cli-init-report", "schemas/init_report.jtd.json", "many"),
        ),
        &[
            "schemas/journal/e1/journal.jtd.json",
            "schemas/init_report.jtd.json",
        ],
    )?;
    let strictness = Strictness::load(root.path())?;
    for rel in [
        "schemas/journal/e1/journal.jtd.json",
        "schemas/init_report.jtd.json",
    ] {
        let schema = root.path().join(rel);
        assert_eq!(
            apply_strictness(WHOLE_FILE, "x/mod.rs", &schema, &strictness)?,
            WHOLE_FILE,
            "`{rel}` is not a `none` role — the bytes do not move"
        );
    }
    Ok(())
}

/// A4.4 — a record whose schema no phase has built yet is skipped by
/// name: the map still builds, the run stays green, and the skip line
/// carries the record id and the path.
#[test]
fn a_record_for_an_unbuilt_schema_is_skipped_by_name() -> Result<()> {
    let root = scratch_root(
        &format!(
            "{}\n{}",
            record("handshake", "schemas/hello/e1/hello.jtd.json", "many"),
            record("cli-init-report", "schemas/init_report.jtd.json", "many"),
        ),
        &["schemas/init_report.jtd.json"], // `hello` is never built
    )?;
    let (strictness, skips) = Strictness::read(root.path())?;
    assert_eq!(skips.len(), 1, "exactly one named skip: {skips:?}");
    assert!(
        skips[0].contains("handshake") && skips[0].contains("schemas/hello/e1/hello.jtd.json"),
        "the skip line names the record and the path: {}",
        skips[0]
    );
    // The built record still rules through the map.
    let schema = root.path().join("schemas").join("init_report.jtd.json");
    assert_eq!(
        apply_strictness(WHOLE_FILE, "init_report/mod.rs", &schema, &strictness)?,
        WHOLE_FILE,
        "a `many` role keeps the file byte for byte"
    );
    Ok(())
}

/// A4.5 — a schema the scanner can see but no record claims refuses:
/// an unregistered format is inexpressible (PROP-044 §4.1), and a
/// silent skip would be a hole exactly where the registry exists.
#[test]
fn a_schema_outside_the_registry_refuses() -> Result<()> {
    let root = scratch_root(
        &record("cli-init-report", "schemas/init_report.jtd.json", "many"),
        &["schemas/init_report.jtd.json", "schemas/stranger.jtd.json"],
    )?;
    let strictness = Strictness::load(root.path())?;
    let err = apply_strictness(
        WHOLE_FILE,
        "stranger/mod.rs",
        &root.path().join("schemas").join("stranger.jtd.json"),
        &strictness,
    )
    .expect_err("an unregistered format is inexpressible");
    let msg = err.to_string();
    assert!(msg.contains("stranger.jtd.json"), "names the schema: {msg}");
    assert!(
        msg.contains("REGISTRY.toml") && msg.contains("PROP-044"),
        "names the registry and the rule: {msg}"
    );
    assert!(
        msg.contains("cargo xtask codegen"),
        "says what to do: {msg}"
    );
    Ok(())
}

/// The `index-entry` / `index-primary` shape: two records claiming one
/// schema with the SAME role are legal and silent — the map is a
/// function, and agreement is not a conflict.
#[test]
fn the_same_role_twice_on_one_schema_is_legal_and_silent() -> Result<()> {
    let root = scratch_root(
        &format!(
            "{}\n{}",
            record("index-entry", "schemas/index/e1/entry.jtd.json", "many"),
            record("index-primary", "schemas/index/e1/entry.jtd.json", "many"),
        ),
        &["schemas/index/e1/entry.jtd.json"],
    )?;
    let (strictness, skips) = Strictness::read(root.path())?;
    assert!(skips.is_empty(), "agreement is not a skip: {skips:?}");
    let schema = root
        .path()
        .join("schemas")
        .join("index")
        .join("e1")
        .join("entry.jtd.json");
    assert_eq!(
        apply_strictness(WHOLE_FILE, "entry/mod.rs", &schema, &strictness)?,
        WHOLE_FILE,
        "the shared `many` role keeps the file byte for byte"
    );
    Ok(())
}

/// Records with `schema = "none"` are skipped silently — they name
/// authored formats with no generated output, and there is nothing to
/// say about a file that will never exist.
#[test]
fn records_without_a_schema_are_skipped_silently() -> Result<()> {
    let root = scratch_root(
        &format!(
            "{}\n{}",
            record("manifest", "none", "many"),
            record("config", "none", "none"),
        ),
        &[],
    )?;
    let (_, skips) = Strictness::read(root.path())?;
    assert!(skips.is_empty(), "no schema means no skip line: {skips:?}");
    Ok(())
}

/// The second run over the pass's own output is the identity — an
/// already-stamped struct is recognised and left alone, so
/// `check-codegen` cannot oscillate between two forms of one file.
#[test]
fn the_pass_is_idempotent() -> Result<()> {
    let root = scratch_root(
        &record("config", "schemas/config.jtd.json", "none"),
        &["schemas/config.jtd.json"],
    )?;
    let strictness = Strictness::load(root.path())?;
    let schema = root.path().join("schemas").join("config.jtd.json");
    let once = apply_strictness(WHOLE_FILE, "config/mod.rs", &schema, &strictness)?;
    let twice = apply_strictness(&once, "config/mod.rs", &schema, &strictness)?;
    assert_eq!(once, twice);
    Ok(())
}

/// A `pub struct` with no derive line directly above refuses loudly,
/// naming the file and the line: the emission shape is pinned, and a
/// struct the pass cannot explain means the pin moved — the one
/// unacceptable answer is a silent partial stamp.
#[test]
fn a_struct_without_the_pinned_derive_line_refuses() -> Result<()> {
    let root = scratch_root(
        &record("config", "schemas/config.jtd.json", "none"),
        &["schemas/config.jtd.json"],
    )?;
    let strictness = Strictness::load(root.path())?;
    let schema = root.path().join("schemas").join("config.jtd.json");
    let src = "pub struct Drifted {\n    pub entries: u32,\n}\n";
    let err = apply_strictness(src, "config/mod.rs", &schema, &strictness)
        .expect_err("a bare struct is not the pinned emission");
    let msg = err.to_string();
    assert!(
        msg.contains("config/mod.rs:1"),
        "names file and line: {msg}"
    );
    assert!(
        msg.contains("strictness.rs") && msg.contains("cargo xtask codegen"),
        "says what to do: {msg}"
    );
    Ok(())
}
