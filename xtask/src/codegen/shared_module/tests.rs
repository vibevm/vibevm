/// Stats for one module: N declarations before, M after, R replaced.
fn stats(before: &[&str], after: &[&str], replaced: usize) -> RewireStats {
    RewireStats {
        before: before.len(),
        after: after.len(),
        replaced,
        names_before: closure(before),
        names_after: closure(after),
    }
}

#[test]
fn the_counter_accepts_a_consistent_run() -> Result<()> {
    let shared = closure(&["PackageKind", "Version"]);
    let per_module = vec![
        stats(&["ByCap", "PackageKind", "Version"], &["ByCap"], 2),
        stats(&["ListReport", "PackageKind"], &["ListReport"], 1),
    ];
    check_counter(&per_module, &shared)?;
    Ok(())
}

#[test]
fn the_counter_refuses_a_drop_that_disagrees_with_the_replacements() -> Result<()> {
    let shared = closure(&["PackageKind"]);
    // One module's `after` count did not move with its replacement: the
    // invariant is fabricated broken here exactly as a replacement bug
    // would fabricate it in the run.
    let per_module = vec![
        stats(&["ByCap", "PackageKind"], &["ByCap"], 1),
        stats(
            &["ListReport", "PackageKind"],
            &["ListReport", "PackageKind"],
            1,
        ),
    ];
    let err = check_counter(&per_module, &shared)
        .expect_err("a drop that disagrees with the replacement count refuses");
    let msg = err.to_string();
    assert!(
        msg.contains("4 declarations before"),
        "totals the before: {msg}"
    );
    assert!(msg.contains("3 after"), "totals the after: {msg}");
    assert!(
        msg.contains("2 copies replaced"),
        "totals the replacements: {msg}"
    );
    Ok(())
}

#[test]
fn the_counter_refuses_a_moved_name_set() -> Result<()> {
    // A shared home carrying a fragment no schema pulls mints a name
    // nobody asked for; a home missing one breaks the modules' types.
    let shared = closure(&["PackageKind", "Orphan", "Missing"]);
    let per_module = vec![stats(&["ByCap", "PackageKind"], &["ByCap"], 1)];
    let err = check_counter(&per_module, &shared).expect_err("a name set that moved refuses");
    let msg = err.to_string();
    assert!(msg.contains("Orphan"), "names the appeared name: {msg}");
    assert!(msg.contains("Missing"), "names the appeared name: {msg}");
    Ok(())
}
