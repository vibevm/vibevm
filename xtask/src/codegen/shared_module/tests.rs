//! Tests for the shared module's two halves — emission (the parasitic
//! root and its stranded import) and replacement (the re-export swap
//! and its refusals) — plus the strictness guard and the counter, the
//! two halves that live in the parent. The fixtures are emission-shaped
//! text, so the tests drive exactly what the passes drive; the block
//! bodies are deliberately small, because the passes key on shape, not
//! on how many fields a struct carries.

use std::collections::BTreeSet;
use std::path::PathBuf;

use super::emit::strip_parasitic_root;
use super::rewire::SharedModule;
use super::{RewireStats, check_counter, prune_orphan_imports, refuse_strictness_divergence};
use anyhow::Result;

/// The `PackageKind` block as both files carry it — an opened
/// vocabulary: the serde derive is off, two hand-rolled impls follow
/// the enum, and all of it moves together or none of it does.
const PACKAGE_KIND: &str = "/// Installable package kind.\n\
#[derive(Debug, Clone, PartialEq, Eq)]\n\
pub enum PackageKind {\n    \
Feat,\n    \
Unknown(String),\n\
}\n\
\n\
impl Serialize for PackageKind {\n    \
fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>\n    \
where\n        \
S: serde::Serializer,\n    \
{\n        \
serializer.serialize_str(\"feat\")\n    \
}\n\
}\n\
\n\
impl<'de> Deserialize<'de> for PackageKind {\n    \
fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>\n    \
where\n        \
D: serde::Deserializer<'de>,\n    \
{\n        \
Ok(PackageKind::Feat)\n    \
}\n\
}\n";

/// The `FeaturesEntry` block as both files carry it — a struct whose
/// body is the last user of `BTreeMap` in a schema module that keeps
/// only its root type.
const FEATURES_ENTRY: &str = "/// Feature table.\n\
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n\
pub struct FeaturesEntry {\n    \
#[serde(default, skip_serializing_if = \"BTreeMap::is_empty\")]\n    \
pub features: BTreeMap<String, Vec<String>>,\n\
}\n";

/// The `Version` alias as both files carry it.
const VERSION: &str = "/// Semantic version string.\npub type Version = semver::Version;\n";

/// The shared module: every fragment's block, once, under the header
/// the generator writes.
fn shared_text() -> String {
    format!(
        "// Code generated by jtd-codegen for Rust v0.2.1\n\n\
use serde::{{Deserialize, Serialize}};\n\
use std::collections::BTreeMap;\n\n\
{FEATURES_ENTRY}\n\
{PACKAGE_KIND}\n\
{VERSION}"
    )
}

/// A schema module pulling all three fragments: the root struct stays,
/// the three blocks go, and `BTreeMap` loses its last user with them.
fn module_text() -> String {
    format!(
        "// Code generated by jtd-codegen for Rust v0.2.1\n\n\
use serde::{{Deserialize, Serialize}};\n\
use std::collections::BTreeMap;\n\n\
/// One row of the capability index.\n\
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n\
pub struct ByCap {{\n    \
pub kind: PackageKind,\n\n    \
pub version: Version,\n\
}}\n\n\
{FEATURES_ENTRY}\n\
{PACKAGE_KIND}\n\
{VERSION}"
    )
}

/// Write a fixture module and load the shared home beside it — the
/// pair every replacement test starts from.
fn fixtures(
    module_body: &str,
    shared_body: &str,
) -> Result<(tempfile::TempDir, PathBuf, SharedModule)> {
    let dir = tempfile::tempdir()?;
    let module = dir.path().join("by_cap").join("mod.rs");
    std::fs::create_dir_all(module.parent().unwrap_or(dir.path()))?;
    std::fs::write(&module, module_body)?;
    let shared_file = dir.path().join("shared").join("mod.rs");
    std::fs::create_dir_all(shared_file.parent().unwrap_or(dir.path()))?;
    std::fs::write(&shared_file, shared_body)?;
    let shared = SharedModule::load(&shared_file)?;
    Ok((dir, module, shared))
}

/// The closure every happy-path test pulls.
fn closure(names: &[&str]) -> BTreeSet<String> {
    names.iter().map(|name| name.to_string()).collect()
}

#[test]
fn rewire_replaces_blocks_with_re_exports() -> Result<()> {
    let (_dir, module, shared) = fixtures(&module_text(), &shared_text())?;
    let stats = shared.rewire(
        &module,
        PathBuf::from("schemas/by_cap.jtd.json").as_path(),
        &closure(&["features_entry", "package_kind", "version"]),
    )?;
    assert_eq!(stats.before, 4, "root struct plus three copies");
    assert_eq!(stats.after, 1, "only the root struct stays");
    assert_eq!(stats.replaced, 3);
    let out = std::fs::read_to_string(&module)?;
    // The root survived untouched, still naming the re-exported types.
    assert!(
        out.contains("pub struct ByCap {"),
        "the local root stays: {out}"
    );
    assert!(
        out.contains("pub kind: PackageKind,"),
        "its fields still name the types: {out}"
    );
    // Three re-exports, in declaration order.
    let features = out
        .find("pub use crate::generated::shared::FeaturesEntry;")
        .expect("FeaturesEntry re-exported");
    let kind = out
        .find("pub use crate::generated::shared::PackageKind;")
        .expect("PackageKind re-exported");
    let version = out
        .find("pub use crate::generated::shared::Version;")
        .expect("Version re-exported");
    assert!(
        features < kind && kind < version,
        "re-exports stand in declaration order: {out}"
    );
    // The copies and their impls are gone — an impl left behind would
    // be a second impl of one trait for the shared type.
    assert!(
        !out.contains("impl Serialize for PackageKind"),
        "impls move with the type: {out}"
    );
    assert!(
        !out.contains("pub enum PackageKind"),
        "the copy is gone: {out}"
    );
    // `BTreeMap` lost its last user; `serde` did not.
    assert!(
        !out.contains("BTreeMap"),
        "the orphaned import is gone: {out}"
    );
    assert!(
        out.contains("use serde::{Deserialize, Serialize};"),
        "the used import stays: {out}"
    );
    Ok(())
}

#[test]
fn rewire_refuses_a_block_that_diverges() -> Result<()> {
    let divergent = module_text().replacen(
        "/// Feature table.",
        "/// Feature table (local annotation).",
        1,
    );
    let (_dir, module, shared) = fixtures(&divergent, &shared_text())?;
    let err = shared
        .rewire(
            &module,
            PathBuf::from("schemas/by_cap.jtd.json").as_path(),
            &closure(&["features_entry", "package_kind", "version"]),
        )
        .expect_err("a copy that differs by a byte is not a copy");
    let msg = err.to_string();
    assert!(msg.contains("FeaturesEntry"), "names the type: {msg}");
    assert!(
        msg.contains("not byte-identical"),
        "names the divergence: {msg}"
    );
    assert!(
        msg.contains("Feature table (local annotation).") && msg.contains("/// Feature table."),
        "names the first diverging line from both sides: {msg}"
    );
    Ok(())
}

#[test]
fn rewire_refuses_a_block_missing_from_the_shared_home() -> Result<()> {
    // A shared home that predates the `version` fragment.
    let stale = format!(
        "// Code generated by jtd-codegen for Rust v0.2.1\n\n\
use serde::{{Deserialize, Serialize}};\n\n\
{PACKAGE_KIND}"
    );
    let (_dir, module, shared) = fixtures(&module_text(), &stale)?;
    let err = shared
        .rewire(
            &module,
            PathBuf::from("schemas/by_cap.jtd.json").as_path(),
            &closure(&["package_kind", "version"]),
        )
        .expect_err("a closure name with no shared block refuses");
    let msg = err.to_string();
    assert!(msg.contains("version"), "names the fragment: {msg}");
    assert!(msg.contains("Version"), "names the type: {msg}");
    assert!(msg.contains("shared"), "names the shared module: {msg}");
    Ok(())
}

