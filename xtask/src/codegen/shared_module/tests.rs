#[test]
fn the_strip_removes_the_parasitic_root_and_its_import() -> Result<()> {
    let src = format!(
        "// Code generated by jtd-codegen for Rust v0.2.1\n\n\
use serde::{{Deserialize, Serialize}};\n\
use serde_json::Value;\n\
use std::collections::BTreeMap;\n\n\
pub type Shared = Option<Value>;\n\n\
{FEATURES_ENTRY}"
    );
    let out = strip_parasitic_root(&src, "shared/mod.rs")?;
    assert!(
        !out.contains("pub type Shared"),
        "the parasitic root is gone: {out}"
    );
    assert!(
        !out.contains("serde_json"),
        "the import it stranded is gone: {out}"
    );
    assert!(
        out.contains("use serde::{Deserialize, Serialize};"),
        "an import with a user stays: {out}"
    );
    assert!(
        out.contains("pub struct FeaturesEntry"),
        "the definitions stay: {out}"
    );
    // No double blank where the root stood.
    assert!(!out.contains("\n\n\n"), "no stranded blank pair: {out}");
    Ok(())
}

#[test]
fn the_strip_keeps_an_import_the_definitions_still_use() -> Result<()> {
    let src = "// Code generated by jtd-codegen for Rust v0.2.1\n\n\
use serde::{Deserialize, Serialize};\n\
use serde_json::Value;\n\n\
pub type Shared = Option<Value>;\n\n\
/// A free-form projection.\n\
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n\
pub struct FreeForm {\n    \
pub extra: Option<Value>,\n\
}\n";
    let out = strip_parasitic_root(src, "shared/mod.rs")?;
    assert!(
        !out.contains("pub type Shared"),
        "the parasitic root is gone: {out}"
    );
    assert!(
        out.contains("use serde_json::Value;"),
        "an import with a user left stays — that is not an error: {out}"
    );
    Ok(())
}

