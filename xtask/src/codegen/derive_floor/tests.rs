//! Unit tests for the trait-floor pass — one per behaviour the pass
//! owes, plus the two shapes only its neighbours produce.
//!
//! Like the sibling passes' tests these drive the production driver
//! `rewrite_generated` over scratch files rather than the pass in
//! isolation, so a green here is a green of the whole pipeline in its
//! recorded order — which matters more for this pass than for any
//! other, because it is the one whose output another pass reads. The
//! scratch `resolved` document rides on a real registered schema's
//! claim, because the strictness pass refuses a schema no
//! `formats/REGISTRY.toml` record names.

use anyhow::Result;
use serde_json::{Value, json};

use crate::codegen::postproc::{StrictnessSource, rewrite_generated};
use crate::codegen::strictness::Strictness;
use crate::repo_root;

/// Drive the production pipeline over a one-off emission and resolved
/// document, exactly as the domain-types tests do.
fn through_pipeline(src: &str, doc: Value, root_stem: &str) -> Result<String> {
    let dir = tempfile::tempdir()?;
    let file = dir.path().join("mod.rs");
    std::fs::write(&file, src)?;
    let resolved = dir.path().join(format!("{root_stem}.jtd.json"));
    std::fs::write(&resolved, serde_json::to_string(&doc)?)?;
    let root = repo_root()?;
    let strictness = Strictness::load(&root)?;
    let schema = root
        .join("schemas")
        .join("index")
        .join("e1")
        .join("by_purl.jtd.json");
    rewrite_generated(
        &file,
        &resolved,
        &schema,
        StrictnessSource::Registry {
            registry: &strictness,
            projections: &[],
        },
    )?;
    Ok(std::fs::read_to_string(&file)?)
}

/// A struct in the pinned emission shape: the derive line the generator
/// writes, then the declaration.
const STRUCT_EMISSION: &str = r#"// Code generated by jtd-codegen for Rust v0.2.1

use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize)]
pub struct Widget {
    #[serde(rename = "name")]
    pub name: String,
}
"#;

/// The schema behind `STRUCT_EMISSION` — one required string member,
/// which needs no policy annotation of any kind.
fn struct_doc() -> Value {
    json!({ "properties": { "name": { "type": "string" } } })
}

/// The floor lands on an ordinary struct, and the serde pair stays
/// where the generator put it.
#[test]
fn a_struct_takes_the_floor_beside_the_serde_pair() -> Result<()> {
    let out = through_pipeline(STRUCT_EMISSION, struct_doc(), "widget")?;
    assert!(
        out.contains("#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]"),
        "the floor did not land:\n{out}"
    );
    assert!(
        !out.contains("#[derive(Serialize, Deserialize)]"),
        "a pristine derive line survived:\n{out}"
    );
    Ok(())
}

/// Everything that is not a derive line is copied byte for byte — the
/// pass has no opinion about declarations, fields, attributes or
/// layout.
#[test]
fn nothing_but_the_derive_line_moves() -> Result<()> {
    let out = through_pipeline(STRUCT_EMISSION, struct_doc(), "widget")?;
    // The identity rename is dropped by the snake_case pass upstream —
    // stated here rather than papered over, because an expectation that
    // silently absorbed a neighbour's edit would stop being a statement
    // about this pass at all.
    let expected = r#"// Code generated by jtd-codegen for Rust v0.2.1

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Widget {
    pub name: String,
}
"#;
    assert_eq!(out, expected);
    Ok(())
}

/// A CLOSED vocabulary is replayed by the vocabulary pass, so it must
/// come out wearing the full floor — the replay path and the rewritten
/// path have to agree.
#[test]
fn a_closed_vocabulary_keeps_the_whole_floor() -> Result<()> {
    let src = r#"// Code generated by jtd-codegen for Rust v0.2.1

use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize)]
pub enum Shape {
    #[serde(rename = "flat")]
    Flat,

    #[serde(rename = "round")]
    Round,
}
"#;
    let doc = json!({
        "definitions": {
            "shape": {
                "metadata": { "x-vocabulary": "closed" },
                "enum": ["flat", "round"]
            }
        },
        "properties": {}
    });
    let out = through_pipeline(src, doc, "holder")?;
    assert!(
        out.contains("#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]"),
        "the closed vocabulary lost the floor:\n{out}"
    );
    Ok(())
}

/// An OPENED vocabulary loses the serde derive — it would collide with
/// the hand-rolled impls — and keeps everything else. This is the
/// behaviour the two passes have to agree on, and the reason the floor
/// literal lives in exactly one module.
#[test]
fn an_opened_vocabulary_loses_only_the_serde_pair() -> Result<()> {
    let src = r#"// Code generated by jtd-codegen for Rust v0.2.1

use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize)]
pub enum Shape {
    #[serde(rename = "flat")]
    Flat,

    #[serde(rename = "round")]
    Round,
}
"#;
    let doc = json!({
        "definitions": {
            "shape": {
                "metadata": { "x-vocabulary": "open" },
                "enum": ["flat", "round"]
            }
        },
        "properties": {}
    });
    let out = through_pipeline(src, doc, "holder")?;
    assert!(
        out.contains("#[derive(Debug, Clone, PartialEq, Eq)]\npub enum Shape {"),
        "the opened vocabulary did not keep the serde-free floor:\n{out}"
    );
    assert!(
        out.contains("impl Serialize for Shape"),
        "the hand-rolled impls are missing:\n{out}"
    );
    assert!(
        !out.contains(
            "#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\npub enum Shape"
        ),
        "the serde derive survived beside the hand-rolled impls:\n{out}"
    );
    Ok(())
}

/// A discriminator union is copied through by the vocabulary pass, so
/// it too must reach the file wearing the floor — its arms are boxed
/// payloads, and `Box<T>` carries every trait `T` carries.
#[test]
fn a_discriminator_union_takes_the_floor_too() -> Result<()> {
    let src = r#"// Code generated by jtd-codegen for Rust v0.2.1

use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize)]
#[serde(tag = "kind")]
pub enum Event {
    #[serde(rename = "made")]
    Made(EventMade),
}

#[derive(Serialize, Deserialize)]
pub struct EventMade {
    #[serde(rename = "name")]
    pub name: String,
}
"#;
    let doc = json!({
        "definitions": {
            "event": {
                "discriminator": "kind",
                "mapping": { "made": { "properties": { "name": { "type": "string" } } } }
            }
        },
        "properties": {}
    });
    let out = through_pipeline(src, doc, "holder")?;
    let floored = out
        .matches("#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]")
        .count();
    assert_eq!(
        floored, 2,
        "both the union and its arm need the floor:\n{out}"
    );
    assert!(
        out.contains("Made(Box<EventMade>)"),
        "the boxing pass did not run before the floor:\n{out}"
    );
    Ok(())
}
