//! Refresh generated worker types before Claude discovers them at startup.

specmark::scope!("spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES");

use std::path::Path;

use vibe_workspace::system_prompt::HarnessKind;
use vibe_workspace::system_prompt::agent_types::{
    AgentTypeStatus, SyncMode, builtin_agent_types, withdraw_lane_types,
};

use crate::commands::prompt;
use crate::output;
use crate::output::language::{self, Glyph, Meta};

const NO_LANE: &str = "this launch passes no lane file, so there is no worker type";

pub(super) fn withdraw(ctx: &output::Context, kind: HarnessKind, selected: &prompt::Selected) {
    if kind != HarnessKind::Claude {
        return;
    }
    match withdraw_lane_types(&selected.node_dir, &builtin_agent_types()) {
        Ok(outcomes) => {
            for outcome in outcomes {
                if outcome.status == AgentTypeStatus::Removed {
                    ctx.block_err(&type_row("removed", &outcome.file));
                }
            }
        }
        Err(error) => {
            ctx.diagnostic(&format!(
                "subagent types were not refreshed ({error:#}); the session starts without fresh vibe types"
            ));
        }
    }
}

pub(super) fn refresh(
    ctx: &output::Context,
    kind: HarnessKind,
    selected: &prompt::Selected,
    lane: Option<&Path>,
) {
    if kind != HarnessKind::Claude {
        return;
    }
    match prompt::refresh_agent_types(
        selected,
        lane.ok_or_else(|| NO_LANE.to_owned()),
        SyncMode::Write,
    ) {
        Ok(outcomes) => {
            for outcome in outcomes {
                let file = outcome.file;
                let status = outcome.status;
                match status {
                    AgentTypeStatus::Created
                    | AgentTypeStatus::Updated
                    | AgentTypeStatus::Removed => {
                        ctx.block_err(&type_row(status.as_str(), &file));
                    }
                    AgentTypeStatus::Foreign => {
                        ctx.diagnostic(&format!(
                            "{file} was not generated by vibe, so this launch leaves it alone; rename or delete it to get the generated type"
                        ));
                    }
                    _ => {}
                }
            }
        }
        Err(error) => {
            ctx.diagnostic(&format!(
                "subagent types were not refreshed ({error:#}); the session starts without fresh vibe types"
            ));
        }
    }
}

fn type_row(status: &str, file: &str) -> String {
    language::Block::new(Glyph::Done, format!("subagent type  {status}"))
        .with_meta(vec![Meta::note(file)])
        .render()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn subagent_type_row_is_a_step_row() {
        assert_eq!(
            type_row("created", ".claude/agents/vibe-worker.md"),
            "✓ subagent type  created · .claude/agents/vibe-worker.md"
        );
    }
}
