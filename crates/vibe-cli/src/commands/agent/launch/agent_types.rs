//! Refresh generated worker types before Claude discovers them at startup.

specmark::scope!("spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES");

use std::path::Path;

use vibe_workspace::system_prompt::HarnessKind;
use vibe_workspace::system_prompt::agent_types::{AgentTypeStatus, SyncMode};

use crate::commands::prompt;
use crate::output;

const NO_LANE: &str = "this launch passes no lane file, so there is no worker type";

pub(super) fn refresh(
    ctx: &output::Context,
    kind: HarnessKind,
    selected: &prompt::Selected,
    lane: Option<&Path>,
) {
    if kind != HarnessKind::Claude {
        return;
    }
    match prompt::refresh_agent_types(
        selected,
        lane.ok_or_else(|| NO_LANE.to_owned()),
        SyncMode::Write,
    ) {
        Ok(outcomes) => {
            for outcome in outcomes {
                let file = outcome.file;
                let status = outcome.status;
                match status {
                    AgentTypeStatus::Created
                    | AgentTypeStatus::Updated
                    | AgentTypeStatus::Removed
                        if !ctx.is_quiet() =>
                    {
                        eprintln!("note: subagent type `{file}` {}", status.as_str());
                    }
                    AgentTypeStatus::Foreign => {
                        eprintln!(
                            "warning: `{file}` was not generated by vibe, so this launch leaves it alone; rename or delete it to get the generated type"
                        );
                    }
                    _ => {}
                }
            }
        }
        Err(error) => {
            eprintln!(
                "warning: subagent types were not refreshed ({error:#}); the session starts without fresh vibe types"
            );
        }
    }
}
