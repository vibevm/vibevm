//! Publish or inspect this node's generated subagent types without rebuilding its lane.

specmark::scope!("spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES");

use std::path::Path;

use anyhow::{Result, bail};
use specmark::spec;
use vibe_wire::generated::prompt_types as wire;
use vibe_workspace::system_prompt::HarnessKind;
use vibe_workspace::system_prompt::agent_types::{
    AgentTypeOutcome, AgentTypeSources, AgentTypeStatus, CLAUDE_AGENT_TYPES_DIR, LockedSlot,
    SyncMode, builtin_agent_types, sync_agent_types,
};

use crate::output;
use crate::output::language::{Cell, Glyph, List, Meta, Role, Row};

use super::Selected;

pub(crate) const PROTOCOL: &str = "vibe-prompt-types/1";
const READ_DELIVERY: &str = "this node delivers its lane to `claude` by `read`, so there is no lane file to give a worker type";

#[spec(implements = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub(crate) fn refresh_agent_types(
    selected: &Selected,
    lane: Result<&Path, String>,
    mode: SyncMode,
) -> Result<Vec<AgentTypeOutcome>> {
    let locked = vibe_core::manifest::Lockfile::read(selected.workspace.lockfile_path())
        .map(|lockfile| {
            lockfile
                .packages
                .iter()
                .map(|package| LockedSlot {
                    group: package.group.clone(),
                    name: package.name.as_str().to_owned(),
                    version: package.version.clone(),
                })
                .collect()
        })
        .map_err(|_| "no readable vibe.lock; run `vibe install`".to_owned());
    let sources = AgentTypeSources {
        lane: lane.and_then(|path| std::fs::read(path).map_err(|error| error.to_string())),
        workspace_root: selected.workspace.root.clone(),
        locked,
    };
    Ok(sync_agent_types(
        &selected.node_dir,
        &builtin_agent_types(),
        &|body| sources.resolve(body),
        mode,
    )?)
}

#[spec(implements = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub(crate) fn run(ctx: &output::Context, selected: &Selected, check: bool) -> Result<()> {
    let composed = super::compose_launch_flags(ctx, selected, HarnessKind::Claude, None, &[])?;
    let lane = if let Some(undeliverable) = &composed.undeliverable {
        Err(undeliverable.sentence())
    } else if let Some(path) = &composed.lane {
        Ok(path.as_path())
    } else {
        Err(READ_DELIVERY.to_owned())
    };
    let outcomes = refresh_agent_types(
        selected,
        lane,
        if check {
            SyncMode::Check
        } else {
            SyncMode::Write
        },
    )?;
    let report = wire::PromptTypesReport {
        protocol: PROTOCOL.to_owned(),
        node: selected.node_rel.clone(),
        harness: "claude".to_owned(),
        mode: if check { "check" } else { "write" }.to_owned(),
        directory: CLAUDE_AGENT_TYPES_DIR.to_owned(),
        types: outcomes
            .iter()
            .map(|outcome| wire::AgentType {
                name: outcome.name.clone(),
                file: outcome.file.clone(),
                status: outcome.status.as_str().to_owned(),
                reason: outcome.reason.clone(),
            })
            .collect(),
    };
    if ctx.is_json() {
        ctx.emit_json(&report)?;
    } else {
        ctx.block(&type_list(&outcomes).render());
    }
    if check {
        let noncurrent = outcomes
            .iter()
            .filter(|outcome| {
                matches!(
                    outcome.status,
                    AgentTypeStatus::Stale | AgentTypeStatus::Missing | AgentTypeStatus::Foreign
                )
            })
            .map(|outcome| format!("{} ({})", outcome.file, outcome.status.as_str()))
            .collect::<Vec<_>>();
        if !noncurrent.is_empty() {
            bail!("{}", not_current_refusal(&noncurrent));
        }
    } else {
        if let Some(foreign) = outcomes
            .iter()
            .find(|outcome| outcome.status == AgentTypeStatus::Foreign)
        {
            bail!(
                "subagent_type_foreign: {} was not generated by vibe, so vibe leaves it alone (violates spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES; fix: rename or delete it, then run `vibe prompt types`)",
                foreign.file
            );
        }
        let count = outcomes
            .iter()
            .filter(|outcome| {
                matches!(
                    outcome.status,
                    AgentTypeStatus::Created | AgentTypeStatus::Updated | AgentTypeStatus::Removed
                )
            })
            .count();
        if count > 0 {
            let plural = if count == 1 { "" } else { "s" };
            ctx.trailer(&format!(
                "wrote {count} subagent type{plural} · {CLAUDE_AGENT_TYPES_DIR}/"
            ));
        } else {
            ctx.trailer(&format!(
                "subagent types current · {CLAUDE_AGENT_TYPES_DIR}/"
            ));
        }
    }
    Ok(())
}

/// Draw each type's observed state without changing its outcome.
#[spec(implements = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
fn type_list(outcomes: &[AgentTypeOutcome]) -> List {
    let rows = outcomes
        .iter()
        .map(|outcome| {
            let (glyph, role) = match outcome.status {
                AgentTypeStatus::Created
                | AgentTypeStatus::Updated
                | AgentTypeStatus::Removed
                | AgentTypeStatus::Unchanged
                | AgentTypeStatus::Current => (Glyph::Done, Role::Ok),
                AgentTypeStatus::Stale | AgentTypeStatus::Missing | AgentTypeStatus::Foreign => {
                    (Glyph::Failed, Role::Alert)
                }
                AgentTypeStatus::Unavailable => (Glyph::Skipped, Role::Dim),
            };
            let mut row = Row::new(vec![Cell::text(&outcome.file)])
                .glyph(glyph, role)
                .meta(vec![Meta::State(outcome.status.as_str().into())]);
            if let Some(reason) = &outcome.reason {
                row = row.child(reason.replace('`', ""));
            }
            row
        })
        .collect();
    List::new(rows).meta_column()
}

/// Keep the refusal code, count and remedy together for human and JSON errors.
#[spec(implements = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
fn not_current_refusal(noncurrent: &[String]) -> String {
    let n = noncurrent.len();
    let (plural, verb) = if n == 1 { ("", "is") } else { ("s", "are") };
    format!(
        "types_not_current: {n} subagent type{plural} {verb} not current (violates spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES; fix: `vibe prompt types`): {}",
        noncurrent.join(", ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prompt_types_rows_have_glyphs_and_states() {
        let outcomes = vec![
            AgentTypeOutcome {
                name: "vibe-worker".into(),
                file: ".claude/agents/vibe-worker.md".into(),
                status: AgentTypeStatus::Created,
                reason: None,
            },
            AgentTypeOutcome {
                name: "vibe-executor".into(),
                file: ".claude/agents/vibe-executor.md".into(),
                status: AgentTypeStatus::Unavailable,
                reason: Some("`org.vibevm.world/working-rules` is not installed here".into()),
            },
        ];
        let expected = format!(
            "✓ {:<33}[created]\n○ {:<33}[unavailable]\n  └ org.vibevm.world/working-rules is not installed here",
            ".claude/agents/vibe-worker.md", ".claude/agents/vibe-executor.md"
        );
        assert_eq!(type_list(&outcomes).render_at(100), expected);
    }

    #[test]
    fn prompt_types_check_refusal_plural_counts_all_noncurrent_entries() {
        let refusal = crate::output::refusal_of(&anyhow::anyhow!(not_current_refusal(&[
            "worker.md (missing)".to_owned(),
            "executor.md (foreign)".to_owned(),
        ])));
        assert_eq!(refusal.code.as_deref(), Some("types_not_current"));
        assert_eq!(refusal.headline, "2 subagent types are not current");
        assert_eq!(
            refusal.why.as_deref(),
            Some("worker.md (missing), executor.md (foreign)")
        );
    }

    #[test]
    fn prompt_types_check_refusal_has_a_code() {
        let refusal = crate::output::refusal_of(&anyhow::anyhow!(not_current_refusal(&[
            ".claude/agents/vibe-worker.md (missing)".to_owned()
        ])));
        assert_eq!(refusal.code.as_deref(), Some("types_not_current"));
        assert_eq!(refusal.headline, "1 subagent type is not current");
        assert_eq!(refusal.fix, ["vibe prompt types"]);
        assert_eq!(
            refusal.why.as_deref(),
            Some(".claude/agents/vibe-worker.md (missing)")
        );
    }
}
