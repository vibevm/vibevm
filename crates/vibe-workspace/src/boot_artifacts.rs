/// `schema` version of the generated `INDEX.md` manifest (PROP-009 §2.3).
pub const INDEX_SCHEMA: u32 = 1;

/// The header comment line carrying a unit's boot-graph fingerprint
/// (PROP-038 §2.7). Present on a per-unit `INDEX.md` so a later regeneration
/// can skip a unit whose fingerprint is unchanged (§2.8). A leading `#` makes
/// it a TOML comment — invisible to the manifest parser.
pub const FP_MARKER: &str = "# vibe:fp ";

/// Read the fingerprint recorded in a generated artifact's header, if any
/// (PROP-038 §2.7). Returns the trimmed hash after [`FP_MARKER`].
pub fn read_fingerprint(text: &str) -> Option<String> {
    text.lines()
        .find_map(|l| l.trim().strip_prefix(FP_MARKER))
        .map(|s| s.trim().to_string())
}

/// Generated INDEX filename, relative to a node's boot lane.
pub use vibe_core::layout::INDEX_MD as INDEX_FILE;

const INDEX_HEADER_SUFFIX: &str = "\
 — generated by vibe, do not edit.
# The computed boot sequence (PROP-009 §2.3). Read every file the
# `[[entry]]` list names, in order.
#
# `installed:<group>/<name>` is resolved during generation: true
# contributions appear normally; false contributions are absent entirely.
# A `kind = \"static\"` entry: read the file directly. A `kind = \"dynamic\"`
# entry: an INCLUDE resolved at boot — when it also carries
# `when = \"os:<name>\"`, read the file only if the session's operating
# system is <name> (windows / macos / linux), and skip it otherwise.

";

fn index_header() -> String {
    format!("# {}{INDEX_HEADER_SUFFIX}", layout_paths::boot(INDEX_FILE))
}

/// One `[[entry]]` of the generated `INDEX.md` manifest.
#[derive(Debug, Serialize)]
struct IndexEntry {
    /// Path of the boot file, as composed by the engine.
    path: String,
    /// `"static"` — read the file directly — or `"dynamic"` — an INCLUDE
    /// the agent resolves at boot.
    kind: &'static str,
    /// Activation condition for a `dynamic` entry (PROP-009 §2.3) — the
    /// wire string `"os:<name>"`. `None` on a `static` entry or an
    /// unconditional `dynamic` one.
    #[serde(skip_serializing_if = "Option::is_none")]
    when: Option<String>,
}

/// The serialised shape of `INDEX.md`.
#[derive(Debug, Serialize)]
struct IndexManifest {
    schema: u32,
    #[serde(rename = "static", skip_serializing_if = "Option::is_none")]
    static_lane: Option<String>,
    #[serde(rename = "entry", skip_serializing_if = "Vec::is_empty")]
    entries: Vec<IndexEntry>,
}

/// Render the `INDEX.md` TOML manifest for a node's effective boot.
///
/// Pure — the manifest is paths and kinds, no file content. The `static`
/// pointer is present exactly when `boot` has `static`-linked entries.
/// Serialisation is structurally infallible with today's fixed manifest
/// shape; the error is routed anyway so a future shape change degrades
/// to a diagnosis instead of a panic.
pub fn render_index(
    boot: &EffectiveBoot,
    fingerprint: Option<&str>,
) -> Result<String, WorkspaceError> {
    render_index_with_spec_format(boot, fingerprint, SpecFormat::Mixed)
}

/// Render `INDEX.md` with its static pointer following the target format.
pub fn render_index_with_spec_format(
    boot: &EffectiveBoot,
    fingerprint: Option<&str>,
    spec_format: SpecFormat,
) -> Result<String, WorkspaceError> {
    let has_static = boot.static_entries().next().is_some();
    let manifest = IndexManifest {
        schema: INDEX_SCHEMA,
        static_lane: has_static.then(|| static_path(spec_format).to_string()),
        entries: boot
            .dynamic_entries()
            .map(|e| IndexEntry {
                path: e.path.clone(),
                // Every INDEX entry is dynamically linked (read by reference);
                // its read-timing derives from `when` — a conditional entry is
                // a gated INCLUDE ("dynamic"), an unconditional one is read
                // directly ("static"). PROP-009 §2.3.
                kind: if e.when.is_some() {
                    "dynamic"
                } else {
                    "static"
                },
                when: e.when.as_ref().map(ToString::to_string),
            })
            .collect(),
    };
    let body = toml::to_string_pretty(&manifest).map_err(|e| WorkspaceError::IndexRender {
        reason: e.to_string(),
    })?;
    // The fingerprint header (PROP-038 §2.7) — a TOML comment, so the manifest
    // stays parseable. Omitted (`None`) on a node so its INDEX.md is
    // byte-stable; carried on a per-unit INDEX to drive the dirty-subgraph.
    let fp_line = match fingerprint {
        Some(fp) => format!("{FP_MARKER}{fp}\n\n"),
        None => String::new(),
    };
    Ok(format!("{}{fp_line}{body}", index_header()))
}

/// Render `STATIC.md` — the concatenation of the `static`-linked
/// contributions, in composed order. Returns `None` when the node has no
/// static contributions (no `STATIC.md` is generated then).
///
/// A `simple` contribution is carried whole — no tree-shaking, no alias
/// resolution (PROP-035 §3's sense of "verbatim"), though the emitted text
/// is NOT byte-identical to the source: `#embed`s expand, anchors/links
/// qualify, trailing whitespace trims, and the generated framing wraps it.
/// A `normal`
/// one is **compiled** to its `#use`/`#source`-resolved, tree-shaken closure
/// (PROP-035 §8, the compiler's whole-artifact normal input) — so a `normal + static` edge bakes
/// in only what the contract actually reaches, merged, in dependency order,
/// rather than the whole file. `workspace_root` resolves each contribution's
/// path (and every `spec://` a `normal` closure walks) against the
/// materialised dependency tree.
pub fn render_static(
    boot: &EffectiveBoot,
    workspace_root: &Path,
    self_coord: &SelfCoordinate,
) -> Result<Option<String>, WorkspaceError> {
    render_static_with_spec_format(boot, workspace_root, self_coord, SpecFormat::Mixed)
}

/// Render the static lane in the project's effective target format.
pub fn render_static_with_spec_format(
    boot: &EffectiveBoot,
    workspace_root: &Path,
    self_coord: &SelfCoordinate,
    spec_format: SpecFormat,
) -> Result<Option<String>, WorkspaceError> {
    let artifact = compile_static_artifact(boot, workspace_root, self_coord, spec_format)?;
    artifact
        .map(|artifact| {
            String::from_utf8(artifact.into_bytes()).map_err(|error| {
                WorkspaceError::InlineCompile {
                    reason: format!(
                        "the built-in STATIC backend returned non-UTF-8 bytes: {error}"
                    ),
                }
            })
        })
        .transpose()
}

fn compile_static_artifact(
    boot: &EffectiveBoot,
    workspace_root: &Path,
    self_coord: &SelfCoordinate,
    spec_format: SpecFormat,
) -> Result<Option<EmittedArtifact>, WorkspaceError> {
    compile_static_artifact_with(
        boot,
        workspace_root,
        self_coord,
        spec_format,
        compile_artifact,
    )
}

fn compile_static_artifact_with(
    boot: &EffectiveBoot,
    workspace_root: &Path,
    self_coord: &SelfCoordinate,
    spec_format: SpecFormat,
    compiler: impl FnOnce(
        ArtifactPlan,
        &FsSectionSource,
    ) -> Result<EmittedArtifact, ArtifactCompileError>,
) -> Result<Option<EmittedArtifact>, WorkspaceError> {
    let entries: Vec<_> = boot.static_entries().collect();
    if entries.is_empty() {
        return Ok(None);
    }
    let mut inputs = Vec::with_capacity(entries.len());
    for entry in entries {
        let input = if entry.elided {
            ArtifactInput::elided(&entry.origin, &entry.path)
        } else if entry.use_ref {
            let target = hoisted_seed(&entry.origin, &entry.path).ok_or_else(|| {
                WorkspaceError::InlineCompile {
                    reason: format!(
                        "cannot derive the hoisted document target for `{}` at `{}`",
                        entry.origin, entry.path
                    ),
                }
            })?;
            ArtifactInput::hoisted(&entry.origin, &entry.path, target)
        } else if entry.format.is_normal() {
            let seed = normal_seed(&entry.origin, &entry.path).ok_or_else(|| {
                WorkspaceError::InlineCompile {
                    reason: format!(
                        "cannot derive a spec:// seed for the normal package `{}` at `{}` \
                         (PROP-035 §8): expected a `<group>/<name>` origin and a path under a \
                         package's `{}` root",
                        entry.origin,
                        entry.path,
                        layout_paths::slot_specs("<slot>", "")
                    ),
                }
            })?;
            ArtifactInput::normal(&entry.origin, &entry.path, seed)
        } else {
            let absolute = workspace_root.join(&entry.path);
            let (markdown, _) =
                vibe_specdoc::load_spec_text(&absolute).map_err(|error| WorkspaceError::Io {
                    path: absolute,
                    reason: error.to_string(),
                })?;
            ArtifactInput::simple(&entry.origin, &entry.path, markdown)
        }
        .map_err(|error| WorkspaceError::InlineCompile {
            reason: error.to_string(),
        })?;
        inputs.push(input);
    }
    let target = if matches!(spec_format, SpecFormat::Xml) {
        ArtifactTarget::StaticXml
    } else {
        ArtifactTarget::StaticMarkdown
    };
    let plan = ArtifactPlan::static_lane(
        target,
        static_path(spec_format),
        layout_paths::vibedeps(""),
        inputs,
    )
    .map_err(|error| WorkspaceError::InlineCompile {
        reason: error.to_string(),
    })?;
    let source = FsSectionSource::new(FileResolver::new(workspace_root, self_coord.clone()));
    compiler(plan, &source).map(Some).map_err(|error| {
        let reason = match error {
            ArtifactCompileError::Input { input, source }
                if input.kind == ArtifactInputType::Normal =>
            {
                format!(
                    "compiling the normal package `{}` closure (PROP-035 §8): {source}",
                    input.origin
                )
            }
            error => error.to_string(),
        };
        WorkspaceError::InlineCompile { reason }
    })
}

/// What [`write_boot_artifacts`] wrote — for the caller to report.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WrittenArtifacts {
    /// Absolute path of the generated `INDEX.md` — always written.
    pub index: PathBuf,
    /// Absolute path of the generated `STATIC.md`, when the node had
    /// static contributions; `None` otherwise.
    pub static_lane: Option<PathBuf>,
    /// Absolute paths of the instruction files whose `<vibevm>` block was
    /// written or updated this run; a file already carrying an identical
    /// block is not listed (PROP-012).
    pub redirects: Vec<PathBuf>,
}

/// Generate and write a node's boot artifacts (PROP-009 §2.3): `INDEX.md`
/// always, `STATIC.md` when the node has static contributions, and the
/// `CLAUDE.md` / `AGENTS.md` / `GEMINI.md` redirects.
///
/// `node_dir` is the node's root; `workspace_root` is the absolute
/// workspace root, used to resolve the static contributions' content;
/// `self_coord` is the workspace root's own `<group>/<name>` coordinate
/// (B-031 — the host is a package coordinate), the authority a `spec://`
/// address names to reach the authored specs tree. A stale `STATIC.md`
/// from an earlier generation is removed when the node no longer has static
/// contributions, so it is never read by mistake.
#[spec(
    implements = "spec://org.vibevm.core/vibevm/modules/vibe-workspace/PROP-012#co-tenant",
    r = 1
)]
pub fn write_boot_artifacts(
    node_dir: &Path,
    workspace_root: &Path,
    self_coord: &SelfCoordinate,
    boot: &EffectiveBoot,
) -> Result<WrittenArtifacts, WorkspaceError> {
    write_boot_artifacts_with_spec_format(
        node_dir,
        workspace_root,
        self_coord,
        boot,
        SpecFormat::Mixed,
    )
}

/// Generate boot artifacts with the static lane following `spec_format`.
pub fn write_boot_artifacts_with_spec_format(
    node_dir: &Path,
    workspace_root: &Path,
    self_coord: &SelfCoordinate,
    boot: &EffectiveBoot,
    spec_format: SpecFormat,
) -> Result<WrittenArtifacts, WorkspaceError> {
    // Compile every fallible semantic artifact before touching existing files.
    let index_text = render_index_with_spec_format(boot, None, spec_format)?;
    let static_artifact = compile_static_artifact(boot, workspace_root, self_coord, spec_format)?;
    let boot_dir = node_dir.join(layout::current_boot_dir());

    // INDEX.md — always. A node carries no fingerprint (byte-stable); the
    // per-unit dirty-subgraph (PROP-038 §2.8) is emit-side, in `hybrid_emit`.
    let index = boot_dir.join(INDEX_FILE);

    // The selected STATIC artifact — only when there are static contributions.
    // The generator owns both spellings and always removes the unselected one.
    let static_path = boot_dir.join(static_file(spec_format));
    let stale_path = boot_dir.join(if matches!(spec_format, SpecFormat::Xml) {
        STATIC_FILE
    } else {
        STATIC_XML_FILE
    });
    let redirects = transaction::write_production_with_selectors(
        transaction::ArtifactWrite {
            index_path: &index,
            index_bytes: index_text.as_bytes(),
            static_path: &static_path,
            static_bytes: static_artifact.as_ref().map(EmittedArtifact::bytes),
            stale_path: &stale_path,
        },
        |transaction| {
            redirect::write_redirect_blocks_with_transaction(node_dir, spec_format, transaction)
        },
    )?;
    let static_lane = static_artifact.map(|_| static_path);

    Ok(WrittenArtifacts {
        index,
        static_lane,
        redirects,
    })
}

fn io_err(path: &Path, error: std::io::Error) -> WorkspaceError {
    WorkspaceError::Io {
        path: path.to_path_buf(),
        reason: error.to_string(),
    }
}

