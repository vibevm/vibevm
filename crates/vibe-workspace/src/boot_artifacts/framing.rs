//! Generated comment framing for the format-selected static lane.
//!
//! Markdown and mixed lanes retain their historical bytes. XML lanes route
//! every generated comment through the versioned c1 codec; no caller formats
//! an XML comment directly.

use std::collections::BTreeMap;

use vibe_core::manifest::SpecFormat;
use vibe_spec::RenameEntry;

use super::static_path;
use crate::layout_paths;

#[derive(Clone, Copy)]
enum Layout {
    Inline,
    Block,
}

fn generated_comment(spec_format: SpecFormat, payload: &str, layout: Layout) -> String {
    if matches!(spec_format, SpecFormat::Xml) {
        return format!(
            "<!-- vibe:c1 {} -->",
            vibe_specdoc::encode_generated_xml_comment(payload)
        );
    }
    match layout {
        Layout::Inline => format!("<!-- {payload} -->"),
        Layout::Block => format!("<!-- {payload}\n-->"),
    }
}

pub(super) fn static_header(spec_format: SpecFormat) -> String {
    let payloads = [
        format!(
            "{} — generated by vibe, do not edit.",
            static_path(spec_format)
        ),
        "The static boot lane (PROP-009 §2.3): the highest-priority".to_string(),
        "contributions, compiled anchor-qualified. Read this first, in full.".to_string(),
    ];
    let mut out = String::new();
    for payload in payloads {
        out.push_str(&generated_comment(spec_format, &payload, Layout::Inline));
        out.push('\n');
    }
    out.push('\n');
    out
}

/// The resolution preamble (B-011 §5.1), kept first after the header.
pub(super) fn resolution_preamble(spec_format: SpecFormat) -> String {
    let payload = format!(
        concat!(
            "RESOLUTION RULES — read these five lines before anything else:\n",
            "  1. Labels in this file are qualified: <origin-slug>--<original>. The origin\n",
            "     is named by the provenance comment above each block; the original short\n",
            "     label is the tail after the last `--`.\n",
            "  2. A short label you cannot find here → check the RENAMED ANCHORS table\n",
            "     below for its qualified heirs; never guess among look-alikes.\n",
            "  3. Full spec:// addresses resolve against package SOURCES under {}/,\n",
            "     never against this generated file. This file is a cache, not a target.\n",
            "  4. `#use spec://… as X` binds a file-local alias; `@!X` is a mandatory read\n",
            "     of X's target (same rules as @spec://…). In this compiled file every @!X\n",
            "     is already rewritten to its full address.\n",
            "  5. An ambiguous or unresolvable short reference is an ERROR to surface with\n",
            "     candidates — never silently pick one."
        ),
        layout_paths::vibedeps("")
    );
    format!(
        "{}\n\n",
        generated_comment(spec_format, &payload, Layout::Block)
    )
}

pub(super) fn static_marker(spec_format: SpecFormat, origin: &str, path: &str) -> String {
    generated_comment(
        spec_format,
        &format!("vibe:static {origin} — {path}"),
        Layout::Inline,
    )
}

pub(super) fn elided_marker(spec_format: SpecFormat, origin: &str, path: &str) -> String {
    generated_comment(
        spec_format,
        &format!(
            "vibe:static {origin} — {path}; zone elided: emitted member-by-member in this lane (once-each, B-006)"
        ),
        Layout::Inline,
    )
}

pub(super) fn hoisted_marker(spec_format: SpecFormat, origin: &str) -> String {
    generated_comment(
        spec_format,
        &format!("vibe:hoisted {origin} — text in the root STATIC.md"),
        Layout::Inline,
    )
}

/// The deterministic RENAMED ANCHORS tombstone (PROP-035 §11).
pub(super) fn tombstone(spec_format: SpecFormat, renames: &[(String, RenameEntry)]) -> String {
    let mut groups: BTreeMap<String, Vec<(String, String)>> = BTreeMap::new();
    for (origin, rename) in renames {
        groups
            .entry(rename.original.clone())
            .or_default()
            .push((origin.clone(), rename.qualified.clone()));
    }
    let mut payload = String::from("RENAMED ANCHORS (short → qualified heirs):");
    for (short, mut heirs) in groups {
        heirs.sort();
        let listed = heirs
            .iter()
            .map(|(origin, qualified)| format!("{qualified} ({origin})"))
            .collect::<Vec<_>>()
            .join(", ");
        payload.push_str(&format!("\n  {short} → {listed}"));
    }
    format!(
        "{}\n\n",
        generated_comment(spec_format, &payload, Layout::Block)
    )
}
