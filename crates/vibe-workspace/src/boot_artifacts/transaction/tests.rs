#[test]
fn opaque_custom_compile_and_real_writer_preserve_arbitrary_bytes_without_shipping_controls() {
    let emitted = compile_artifact_opaque_test_vehicle(test_plan(), &NoSource).unwrap();
    assert_eq!(emitted.bytes(), [0x00, 0xff, b'\n']);

    let temp = TempDir::new().unwrap();
    let index = temp.path().join("INDEX.md");
    let selected = temp.path().join("STATIC.md");
    let stale = temp.path().join("STATIC.xml");
    write_production(ArtifactWrite {
        index_path: &index,
        index_bytes: b"INDEX",
        static_path: &selected,
        static_bytes: Some(emitted.bytes()),
        stale_path: &stale,
    })
    .unwrap();
    assert_eq!(fs::read(index).unwrap(), b"INDEX");
    assert_eq!(fs::read(selected).unwrap(), [0x00, 0xff, b'\n']);
}

