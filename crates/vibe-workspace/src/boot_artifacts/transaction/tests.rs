fn spawn_child(root: &Path, direction: Direction, point: WritePoint, rollback: bool) -> ExitStatus {
    Command::new(env::current_exe().unwrap())
        .arg("--exact")
        .arg("boot_artifacts::transaction::tests::transaction_child_helper")
        .arg("--nocapture")
        .env(CHILD_ROOT, root)
        .env(CHILD_DIRECTION, direction.code())
        .env(CHILD_POINT, format!("{point:?}"))
        .env(CHILD_ROLLBACK, if rollback { "1" } else { "0" })
        .status()
        .unwrap()
}

fn assert_interrupted(status: ExitStatus) {
    assert_eq!(status.code(), Some(86), "child status: {status}");
}

struct ChildExit {
    point: WritePoint,
    rollback: bool,
}

impl FaultInjector for ChildExit {
    fn check(&self, point: WritePoint, path: &Path) -> Result<(), WorkspaceError> {
        if self.rollback && point == WritePoint::IndexReplace {
            return Err(injected(path, "child primary failure"));
        }
        if point == self.point {
            if self.rollback {
                fs::write(
                    path.parent().unwrap().join("ROLLBACK-MUTATED"),
                    path.display().to_string(),
                )
                .unwrap();
            }
            std::process::exit(86);
        }
        Ok(())
    }
}

#[test]
fn transaction_child_helper() {
    let Ok(root) = env::var(CHILD_ROOT) else {
        return;
    };
    let direction = Direction::parse(&env::var(CHILD_DIRECTION).unwrap());
    let point = parse_point(&env::var(CHILD_POINT).unwrap());
    let rollback = env::var(CHILD_ROLLBACK).unwrap() == "1";
    let fixture = Fixture {
        index: PathBuf::from(&root).join("INDEX.md"),
        selected: PathBuf::from(&root).join(direction.new_name()),
        stale: PathBuf::from(&root).join(direction.old_name()),
        old_index: index_bytes(direction.old_name()),
        new_index: index_bytes(direction.new_name()),
    };
    let result = write_with_faults(fixture.write(), &ChildExit { point, rollback });
    panic!("child reached the end instead of interruption: {result:?}");
}

fn parse_point(value: &str) -> WritePoint {
    match value {
        "PostStagePreReplace" => WritePoint::PostStagePreReplace,
        "PostStaticPreIndex" => WritePoint::PostStaticPreIndex,
        "PostIndexPreStaleCleanup" => WritePoint::PostIndexPreStaleCleanup,
        "PostRollbackRestore" => WritePoint::PostRollbackRestore,
        other => panic!("unknown child point {other}"),
    }
}

fn assert_exactly_one_static(root: &Path) {
    let count = static_count(root);
    assert_eq!(count, 1, "STATIC invariant at {}", root.display());
}

fn static_count(root: &Path) -> usize {
    [root.join("STATIC.md"), root.join("STATIC.xml")]
        .iter()
        .filter(|path| fs::symlink_metadata(path).is_ok())
        .count()
}

fn intent_exists(root: &Path) -> bool {
    entry_present(&journal_path(root)) || entry_present(&rollback_journal_path(root))
}

fn entry_present(path: &Path) -> bool {
    match fs::symlink_metadata(path) {
        Ok(_) => true,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => false,
        Err(error) => panic!("metadata for {} failed: {error}", path.display()),
    }
}

fn injected(path: &Path, reason: impl ToString) -> WorkspaceError {
    WorkspaceError::Io {
        path: path.to_path_buf(),
        reason: reason.to_string(),
    }
}

