//! The managed redirect block (PROP-012) — vibevm's `<vibevm>` block in the
//! agent instruction files (`CLAUDE.md` / `AGENTS.md` / `GEMINI.md`).
//!
//! vibevm owns only the delimited block inside each co-tenant file; the rest
//! of every file belongs to the developer and any other tool and is preserved
//! verbatim. PROP-012 §2: a plain line scan finds the `<vibevm>` / `</vibevm>`
//! markers (no markdown parse), absent markers create the block, a present
//! pair splices a fresh body between them touching nothing outside, and a
//! malformed pair is a hard stop. The block body itself ([`render_redirect`])
//! is the PROP-009 §2.3 redirect, unchanged — PROP-012
//! changed the envelope, not the payload.

