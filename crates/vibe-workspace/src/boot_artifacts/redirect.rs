/// What this generation's managed-block write would leave in an instruction
/// file whose current content is `existing` (`None` for a missing file) —
/// computed without touching the filesystem. `Err` carries the
/// malformed-marker reason, which a writing caller turns into a refusal and
/// a reading caller reports as-is.
///
/// This exists as a value, and not only as a side effect of writing,
/// because the prefix's entrypoint witness must be the **prospective** bytes
/// of the same generation: the redirect selector runs after the INDEX and
/// STATIC roll-forwards commit, so witnessing the file as it is now would
/// bind a newly published prefix to the previous generation
/// (PROP-076 `#SYS-PROSPECTIVE-ENTRYPOINT`). One function answers both
/// callers on purpose — a second renderer would drift from this one, and a
/// test asserts the write leaves exactly what this returns.
pub(crate) fn project_managed_block(
    existing: Option<&str>,
    facts: &RouterFacts,
) -> std::result::Result<String, String> {
    let block = render_block(facts);
    let Some(content) = existing else {
        return Ok(block);
    };
    match locate_block(content) {
        BlockLocation::Malformed(reason) => Err(reason),
        BlockLocation::Present { start, end } => {
            let mut out = String::with_capacity(content.len());
            out.push_str(&content[..start]);
            out.push_str(&block);
            out.push_str(&content[end..]);
            Ok(out)
        }
        BlockLocation::Absent => {
            if content.trim().is_empty() || content.trim_start().starts_with(OLD_GENERATED_HEADER) {
                // An empty file, or the pre-PROP-012 whole-file generated
                // redirect — the file was vibevm's, so reclaim it as a
                // block (PROP-012 §4).
                Ok(block)
            } else {
                // Co-tenant content — append the block after it, preserving
                // every existing byte (PROP-012 §2.3).
                let mut out = content.to_owned();
                if !out.ends_with('\n') {
                    out.push('\n');
                }
                out.push('\n');
                out.push_str(&block);
                Ok(out)
            }
        }
    }
}

/// Where vibevm's managed `<vibevm>` block sits in an instruction file
/// (PROP-012 §2.2–§2.3).
#[derive(Debug, Clone, PartialEq, Eq)]
#[spec(
    implements = "spec://org.vibevm.core/vibevm/modules/vibe-workspace/PROP-012#markers",
    r = 1
)]
pub enum BlockLocation {
    /// No `<vibevm>` markers at all — the block is created on write (§2.3).
    Absent,
    /// Exactly one well-formed pair. `[start, end)` is the block's byte
    /// span — the first byte of the `<vibevm>` line to the byte after the
    /// `</vibevm>` line (its newline included when present).
    Present { start: usize, end: usize },
    /// The markers are malformed — not exactly one ordered pair. The
    /// string names the defect for the operator.
    Malformed(String),
}

/// Locate vibevm's managed block in `content` by a plain line scan: a
/// line whose trimmed text equals `<vibevm>` / `</vibevm>` is a marker
/// (PROP-012 §2.2). No markdown parse, no model — the detection that
/// gates a mutating write must be deterministic and trivial.
#[spec(
    implements = "spec://org.vibevm.core/vibevm/modules/vibe-workspace/PROP-012#markers",
    r = 1
)]
pub fn locate_block(content: &str) -> BlockLocation {
    let mut open: Option<(usize, usize)> = None;
    let mut close: Option<(usize, usize)> = None;
    let mut open_lines: Vec<usize> = Vec::new();
    let mut close_lines: Vec<usize> = Vec::new();
    let mut offset = 0usize;
    for (line_no, line) in content.split_inclusive('\n').enumerate() {
        let trimmed = line.strip_suffix('\n').unwrap_or(line).trim();
        if trimmed == BLOCK_OPEN {
            open_lines.push(line_no + 1);
            open.get_or_insert((offset, offset + line.len()));
        } else if trimmed == BLOCK_CLOSE {
            close_lines.push(line_no + 1);
            close.get_or_insert((offset, offset + line.len()));
        }
        offset += line.len();
    }
    // Matching on the recorded spans (not just the counts) lets the
    // compiler carry the "one of each → both recorded" invariant; the
    // impossible counts-without-spans combination falls through to the
    // Malformed arm instead of a panic. A Malformed report names each
    // marker's line — the drill's precision: the operator repairs the
    // file by hand and must not have to search for the markers.
    match (open_lines.len(), close_lines.len(), open, close) {
        (0, 0, _, _) => BlockLocation::Absent,
        (1, 1, Some((open_start, _)), Some((close_start, close_end))) => {
            if open_start < close_start {
                BlockLocation::Present {
                    start: open_start,
                    end: close_end,
                }
            } else {
                BlockLocation::Malformed(format!(
                    "the `</vibevm>` marker (line {}) precedes its `<vibevm>` opener (line {})",
                    close_lines[0], open_lines[0]
                ))
            }
        }
        (opens, closes, _, _) => BlockLocation::Malformed(format!(
            "expected zero markers or exactly one `<vibevm>` … `</vibevm>` pair, found \
             {opens} `<vibevm>` marker line(s){} and {closes} `</vibevm>` marker line(s){}",
            at_lines(&open_lines),
            at_lines(&close_lines)
        )),
    }
}

/// Render a marker-line list as ` at line(s) 12, 40` — empty when there
/// are no markers, so a zero count is not followed by an empty list.
fn at_lines(lines: &[usize]) -> String {
    if lines.is_empty() {
        String::new()
    } else {
        let joined = lines
            .iter()
            .map(|l| l.to_string())
            .collect::<Vec<_>>()
            .join(", ");
        format!(" at line(s) {joined}")
    }
}

/// Write vibevm's managed block into the instruction file at `path`
/// (PROP-012 §2.3). Returns the path when the file changed, or `None`
/// when it already carried a byte-identical block (no write — no churn).
///
/// Absent markers → append a fresh block at end of file, preserving every
/// existing byte (or, when the whole file is the pre-PROP-012 generated
/// redirect, replace it wholesale — PROP-012 §4); a missing file is
/// created. Present → splice the new body between the markers, touching
/// nothing outside them. Malformed → [`WorkspaceError::MalformedRedirectBlock`]
/// without writing — callers validate at plan time (PROP-012 §2.4), so
/// this is the defensive last line.
#[cfg(test)]
#[spec(
    implements = "spec://org.vibevm.core/vibevm/modules/vibe-workspace/PROP-012#create",
    r = 1
)]
#[spec(
    implements = "spec://org.vibevm.core/vibevm/modules/vibe-workspace/PROP-012#migration",
    r = 1
)]
fn write_managed_block(path: &Path) -> Result<Option<PathBuf>, WorkspaceError> {
    write_managed_block_for(
        path,
        &RouterFacts::undeclared(SpecFormat::Mixed),
        PROJECT_DOC_MAX_BYTES,
        "redirecttest",
    )
}

fn write_managed_block_for(
    path: &Path,
    facts: &RouterFacts,
    limit: usize,
    transaction: &str,
) -> Result<Option<PathBuf>, WorkspaceError> {
    let existing = match safe_file::read_optional(path).map_err(|error| io_err(path, error))? {
        Some(bytes) => Some(
            String::from_utf8(bytes).map_err(|error| WorkspaceError::Io {
                path: path.to_path_buf(),
                reason: error.to_string(),
            })?,
        ),
        None => None,
    };
    let new_content = project_managed_block(existing.as_deref(), facts).map_err(|reason| {
        WorkspaceError::MalformedRedirectBlock {
            path: path.to_path_buf(),
            reason,
        }
    })?;
    refuse_over_budget(path, &new_content, limit)?;
    if existing.as_deref() == Some(new_content.as_str()) {
        return Ok(None);
    }
    super::transaction::replace_selector(path, new_content.as_bytes(), transaction)?;
    Ok(Some(path.to_path_buf()))
}

/// Codex's silent truncation, as a refusal rather than a surprise (owner
/// decision D11, `#SYS-HARNESS-DELIVERY`).
///
/// A project instruction file past `project_doc_max_bytes` is cut with no
/// notice in the rendered prompt, so a block beyond that offset means a
/// session that boots without its own project's rules and is told nothing.
/// The *near* case is a warning, and a warning needs a report, so it is
/// `vibe check`'s — over the same [`CodexBudget`] classification, which
/// makes the two severities one measurement read twice rather than two
/// limits that can drift.
fn refuse_over_budget(path: &Path, content: &str, limit: usize) -> Result<(), WorkspaceError> {
    let BlockLocation::Present { end, .. } = locate_block(content) else {
        return Ok(());
    };
    let name = path
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("the instruction file");
    let budget = CodexBudget::against(end, limit);
    match budget {
        CodexBudget::Truncated { .. } => Err(WorkspaceError::MalformedRedirectBlock {
            path: path.to_path_buf(),
            reason: budget
                .message(name)
                .unwrap_or_else(|| "the managed block is past the file limit".to_owned()),
        }),
        CodexBudget::Fits | CodexBudget::Near { .. } => Ok(()),
    }
}

/// Write vibevm's managed `<vibevm>` block into every agent instruction
/// file ([`REDIRECT_FILES`]) of the node rooted at `node_dir` (PROP-012).
/// Returns the files actually written — a file already carrying an
/// identical block is left untouched.
pub fn write_redirect_blocks(node_dir: &Path) -> Result<Vec<PathBuf>, WorkspaceError> {
    write_redirect_blocks_with_spec_format(node_dir, SpecFormat::Mixed)
}

/// Write the managed redirects with the selected static-lane target, for a
/// directory whose identity and lane digest are not at hand.
pub fn write_redirect_blocks_with_spec_format(
    node_dir: &Path,
    spec_format: SpecFormat,
) -> Result<Vec<PathBuf>, WorkspaceError> {
    write_redirect_blocks_for(node_dir, &RouterFacts::undeclared(spec_format))
}

/// Write the managed redirects of one node from its own router facts.
pub fn write_redirect_blocks_for(
    node_dir: &Path,
    facts: &RouterFacts,
) -> Result<Vec<PathBuf>, WorkspaceError> {
    write_redirect_blocks_bounded(node_dir, facts, PROJECT_DOC_MAX_BYTES)
}

/// Write the managed redirects of one node, measuring the block against the
/// Codex limit the node's own manifest declares
/// (`[system_prompt.harness.codex] doc_max_bytes`, default
/// [`PROJECT_DOC_MAX_BYTES`]).
pub fn write_redirect_blocks_bounded(
    node_dir: &Path,
    facts: &RouterFacts,
    limit: usize,
) -> Result<Vec<PathBuf>, WorkspaceError> {
    let boot_dir = node_dir.join(vibe_core::layout::current_boot_dir());
    let nonce = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_nanos();
    let transaction = format!("redirect{}{nonce}", std::process::id());
    super::transaction::with_boot_lock(&boot_dir, || {
        write_redirect_blocks_with_transaction(node_dir, facts, limit, &transaction)
    })
}

pub(super) fn write_redirect_blocks_with_transaction(
    node_dir: &Path,
    facts: &RouterFacts,
    limit: usize,
    transaction: &str,
) -> Result<Vec<PathBuf>, WorkspaceError> {
    write_redirect_blocks_with_faults(node_dir, facts, limit, transaction, &NoRedirectFault)
}

trait RedirectFaultInjector {
    fn after_replace(&self, index: usize, path: &Path) -> Result<(), WorkspaceError>;
}

struct NoRedirectFault;

impl RedirectFaultInjector for NoRedirectFault {
    fn after_replace(&self, _index: usize, _path: &Path) -> Result<(), WorkspaceError> {
        Ok(())
    }
}

fn write_redirect_blocks_with_faults(
    node_dir: &Path,
    facts: &RouterFacts,
    limit: usize,
    transaction: &str,
    faults: &impl RedirectFaultInjector,
) -> Result<Vec<PathBuf>, WorkspaceError> {
    let mut written = Vec::new();
    for (index, name) in REDIRECT_FILES.iter().enumerate() {
        let path = node_dir.join(name);
        if let Some(path) = write_managed_block_for(&path, facts, limit, transaction)? {
            written.push(path);
        }
        faults.after_replace(index, &path)?;
    }
    Ok(written)
}

