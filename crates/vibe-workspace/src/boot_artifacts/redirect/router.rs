//! The router — the body of vibevm's managed `<vibevm>` block.
//!
//! Until 2026-11 the block was the PROP-009 §2.3 redirect: "read these files
//! in order". That sentence is false as a description of *time* the moment a
//! harness carries the lane in its own instruction slot, which is what the
//! launch delivery tier of PROP-076 `#SYS-HARNESS-DELIVERY` does. So the
//! body became the **router** of `#SYS-NO-RECURSION`: one byte-identical
//! block for the `read` and the `launch` tier whose test is *presence
//! anywhere in the context*, never position.
//!
//! Three properties are what make one block serve both tiers.
//!
//! - **Its test is presence.** "The lane is somewhere in your context" is
//!   decided by the marker pairs of [`crate::system_prompt`], which a
//!   harness may have concatenated anywhere. Launched through `vibe agent`
//!   the markers are there and the agent reads nothing; launched plain they
//!   are absent and the agent reads the lane. So a project in launch mode
//!   cannot contradict itself, and no positional word ("above", "below",
//!   "you have just read") appears in the text.
//! - **It scopes itself.** It governs only the project whose root holds the
//!   file it sits in, and a task carrying the subagent quiet clause ignores
//!   it entirely — which is what makes a harness's downward discovery of a
//!   sub-directory's or a dependency copy's block harmless rather than a
//!   second set of boot rules.
//! - **It states precedence, not sequence.** PROP-009's start order is an
//!   order of precedence; a lane delivered earlier counts as read
//!   (`#SYS-BOOT-ORDER-IS-PRECEDENCE`).
//!
//! Out of line from [`super`] along its own seam: this module owns the
//! generated prose and the declared facts it is rendered from, while the
//! parent owns the marker scan and the write.

specmark::scope!("spec://org.vibevm.core/vibevm/common/PROP-076#SYS-NO-RECURSION");

use std::sync::OnceLock;

use specmark::spec;
use vibe_core::manifest::{Manifest, SpecFormat};
use vibe_spec::SelfCoordinate;

use super::super::static_path;
use super::{BLOCK_CLOSE, BLOCK_OPEN};
use crate::layout_paths;

/// The generated header of the managed block's body.
const BLOCK_HEADER: &str = "\
<!-- Generated by vibe — do not edit inside this block; it is rewritten on `vibe install`. Text outside the <vibevm> markers is yours. -->";

/// What one node's router block needs to know about its own project.
///
/// Three facts and nothing else, each read from a declaration rather than
/// observed: the node's identity, which `STATIC` spelling this generation
/// publishes, and the delivered digest of that lane. There is deliberately
/// no build time, no absolute path and no host observation in here — the
/// block is written into three git-tracked files, and anything volatile in
/// it would be a diff on every install (`#SYS-NO-VOLATILE`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RouterFacts {
    /// The node's identity, as the lane markers spell it. See
    /// [`router_node_id`] for how a directory with no declaration is spelled.
    pub node_id: String,
    /// The 12 digits of the compiled lane's delivered body
    /// ([`segment_hash12`](crate::system_prompt::segment_hash12)), or `None`
    /// when the node publishes no static lane at all — which is a normal
    /// case and not an empty hash (`#SYS-LANE-SPELLING`).
    pub static_hash12: Option<String>,
    /// The target format this generation publishes the lane under, which
    /// decides whether the block names `STATIC.xml` or `STATIC.md`.
    pub spec_format: SpecFormat,
}

impl RouterFacts {
    /// The facts for a directory whose identity and lane are not at hand —
    /// the shape [`render_redirect`] and the non-traced write path use.
    pub fn undeclared(spec_format: SpecFormat) -> Self {
        Self {
            node_id: UNDECLARED_NODE_ID.to_owned(),
            static_hash12: None,
            spec_format,
        }
    }
}

/// The reserved node-id spelling for a directory that declares no identity.
///
/// No manifest can produce it — a coordinate is a name, optionally a group
/// and a slash — so the router's scope test still fails closed rather than
/// matching some other project's lane by accident. It exists because
/// `write_boot_artifacts` is reachable for a bare directory, and a refusal
/// there would be a refusal to write a boot lane over an identity question
/// the lane itself does not depend on.
pub const UNDECLARED_NODE_ID: &str = "-";

/// The identity a node's router block carries: the node's own declared
/// coordinate, else the workspace's own, else [`UNDECLARED_NODE_ID`].
///
/// One function, because the writer and the prefix's prospective witness
/// must agree to the byte: a second derivation is how a published block and
/// its own witness end up naming two different projects
/// (`#SYS-PROSPECTIVE-ENTRYPOINT`). The declared half is
/// [`Manifest::consumer_node`]'s coordinate rather than a reading of
/// `[project]`/`[package]` of its own, for the same reason.
pub fn router_node_id(manifest: Option<&Manifest>, self_coord: &SelfCoordinate) -> String {
    let declared = manifest
        .and_then(Manifest::consumer_node)
        .map(|node| node.coordinate())
        .filter(|id| !id.is_empty());
    if let Some(id) = declared {
        return id;
    }
    let host = match &self_coord.group {
        Some(group) if !group.is_empty() && !self_coord.name.is_empty() => {
            format!("{group}/{}", self_coord.name)
        }
        _ => self_coord.name.clone(),
    };
    if host.is_empty() {
        UNDECLARED_NODE_ID.to_owned()
    } else {
        host
    }
}

/// The body of vibevm's managed block for a directory whose identity and
/// lane digest are not at hand (PROP-012 §2.5, PROP-076 `#SYS-NO-RECURSION`).
#[spec(
    implements = "spec://org.vibevm.core/vibevm/modules/vibe-workspace/PROP-012#content",
    r = 1
)]
pub fn render_redirect() -> &'static str {
    static BODY: OnceLock<String> = OnceLock::new();
    BODY.get_or_init(|| render_router(&RouterFacts::undeclared(SpecFormat::Mixed)))
        .as_str()
}

/// Render the router with its static pointer following the target format,
/// for a directory whose identity and lane digest are not at hand.
pub fn render_redirect_with_spec_format(spec_format: SpecFormat) -> String {
    render_router(&RouterFacts::undeclared(spec_format))
}

/// Render the router block's body for one node.
///
/// A node with no static lane gets the same five numbered rules in the same
/// order, with the three sentences that name a lane file replaced by ones
/// that say there is none — rather than a shorter block, so that a reader
/// comparing two projects' blocks is comparing the same shape.
pub fn render_router(facts: &RouterFacts) -> String {
    let static_rel = static_path(facts.spec_format);
    let index_rel = layout_paths::boot(vibe_core::layout::INDEX_MD);
    let node_id = &facts.node_id;
    let (lane_sentence, rule_three, rule_four, precedence) = match &facts.static_hash12 {
        Some(hash12) => (
            format!("The boot lane is `{static_rel}`, then every file listed in `{index_rel}`."),
            format!(
                "3. The expected id of `{static_rel}` is `{hash12}`. If its lane lines\n   \
                 carry another id the delivered copy is out of date: read the whole\n   \
                 lane from disk."
            ),
            format!(
                "4. A lane file with no lane lines in your context, and which you have\n   \
                 not already read in this session: read it from disk — `{static_rel}`\n   \
                 first, then INDEX order."
            ),
            format!(
                "The boot order — this file, `{static_rel}`, the INDEX files — is an order of\n\
                 precedence, not of position. A lane delivered before this file has been read."
            ),
        ),
        None => (
            format!(
                "This project publishes no static lane, so its boot lane is every file listed\nin `{index_rel}`."
            ),
            "3. This project publishes no static lane, so there is no expected id to\n   compare."
                .to_owned(),
            "4. A lane file with no lane lines in your context, and which you have\n   \
             not already read in this session: read it from disk, in INDEX order."
                .to_owned(),
            "The boot order — this file, then the INDEX files — is an order of precedence,\n\
             not of position. A lane delivered before this file has been read."
                .to_owned(),
        ),
    };
    format!(
        "{BLOCK_HEADER}

# Session boot — project {node_id}

This block applies only when the directory holding this file is the root of
your session's project. If you found this file in a sub-directory or in a
materialised dependency copy, ignore this block. A task carrying the subagent
quiet clause ignores it as well: its packet names the files it reads.

{lane_sentence} Parts of it may already be in your context, at
any position. A delivered file sits between two lines:

    vibe:lane-begin {node_id} <path> <id>
    vibe:lane-end {node_id} <path> <id>

1. A file with both lines in your context is read. Do not read it again. If
   the same pair appears twice the copies are identical; follow one.
2. A file with a begin line and no end line was cut short. Read it from disk.
{rule_three}
{rule_four}
5. An INDEX row carrying a `when` condition is read only when that condition
   holds for this session.

{precedence}

Boot is pure file-reading — there is nothing to execute."
    )
}

/// The full managed block — the `<vibevm>` marker, the body, the
/// `</vibevm>` marker — as written into an instruction file. Ends with a
/// trailing newline so it slots cleanly into a file.
pub(super) fn render_block(facts: &RouterFacts) -> String {
    let body = render_router(facts);
    format!("{BLOCK_OPEN}\n{body}\n{BLOCK_CLOSE}\n")
}

/// The neutral body a managed block carries in a copy `vibe` materialises
/// under `vibedeps/`.
///
/// A harness that discovers context files downward concatenates a dependency
/// copy's instruction file into the session, and that copy's router would
/// then be a second project's boot rules inside this project's context. The
/// copy keeps its markers and every byte of its surrounding authored text —
/// `vibe` owns only the block — while the block itself says plainly that it
/// does not apply (`#SYS-NO-RECURSION`).
pub const NEUTRALISED_BODY: &str = "\
<!-- Generated by vibe — this is a materialised dependency copy, not a project root. -->

# Not this session's boot

This file is a copy `vibe` materialised under its dependency root. The boot
block it carried belongs to the package it was copied from and not to the
project you are working in, so it has been replaced by this notice. Ignore
it: your own project's instruction file carries the block that applies.";

/// The managed block as a materialised dependency copy carries it.
pub fn render_neutralised_block() -> String {
    format!("{BLOCK_OPEN}\n{NEUTRALISED_BODY}\n{BLOCK_CLOSE}\n")
}

/// Codex truncates a project `AGENTS.md` at `project_doc_max_bytes` — 32 KiB
/// by default — **with no notice in the rendered prompt**, measured by
/// `HARNESS-DELIVERY.md` §5 against a 40 KB file whose tail canary simply
/// vanished.
pub const PROJECT_DOC_MAX_BYTES: usize = 32 * 1024;

/// How close to [`PROJECT_DOC_MAX_BYTES`] the block's end may come before the
/// budget is reported as a warning (owner decision D11).
pub const PROJECT_DOC_WARN_MARGIN: usize = 4 * 1024;

/// Where an instruction file's managed block sits against Codex's silent
/// truncation limit (owner decision D11).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CodexBudget {
    /// The block ends well inside the limit.
    Fits,
    /// The block ends inside the limit but within
    /// [`PROJECT_DOC_WARN_MARGIN`] of it: the next few authored paragraphs
    /// would push the project's own rules out of the prompt.
    Near {
        /// Byte offset just past the block's last byte.
        end: usize,
    },
    /// The block's last byte lies past the limit, so a Codex session boots
    /// without the block at all and nothing says so. A refusal, not a note.
    Truncated {
        /// Byte offset just past the block's last byte.
        end: usize,
    },
}

impl CodexBudget {
    /// Classify the file content `content` whose managed block ends at `end`.
    pub fn of(end: usize) -> Self {
        if end > PROJECT_DOC_MAX_BYTES {
            CodexBudget::Truncated { end }
        } else if end + PROJECT_DOC_WARN_MARGIN > PROJECT_DOC_MAX_BYTES {
            CodexBudget::Near { end }
        } else {
            CodexBudget::Fits
        }
    }

    /// The operator-facing sentence, or `None` when the block fits.
    ///
    /// One wording for both severities, because the fact is one fact: the
    /// writer raises the `Truncated` case as a refusal and `vibe check`
    /// reports the `Near` case as a warning, and a reader comparing the two
    /// messages should see the same measurement.
    pub fn message(self, name: &str) -> Option<String> {
        let (end, verdict) = match self {
            CodexBudget::Fits => return None,
            CodexBudget::Near { end } => (
                end,
                "is within 4 KB of it — a few more authored paragraphs would push the \
                 block out of a Codex session's prompt",
            ),
            CodexBudget::Truncated { end } => (
                end,
                "is past it, so a Codex session reads this file truncated, loses the \
                 block entirely, and is told nothing",
            ),
        };
        Some(format!(
            "the managed `<vibevm>` block of `{name}` ends at byte {end}, and Codex \
             truncates a project instruction file at {PROJECT_DOC_MAX_BYTES} bytes: that {verdict}. \
             Move authored text out of this file, or shorten it."
        ))
    }
}

