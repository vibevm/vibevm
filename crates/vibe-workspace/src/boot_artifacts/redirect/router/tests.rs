//! The router block's own bytes, and the three refusals around them.
//!
//! The phase that writes this block edits the body of every instruction
//! file in every project, and that diff is unreviewable by reading. The
//! guard is therefore that the body comes from one function with a golden
//! test over its bytes: the review is of the function and of this file.

use super::*;
use vibe_core::manifest::{Manifest, TargetOs};

fn facts(node_id: &str, hash12: Option<&str>, spec_format: SpecFormat) -> RouterFacts {
    RouterFacts {
        node_id: node_id.to_owned(),
        static_hash12: hash12.map(str::to_owned),
        spec_format,
    }
}

/// The whole body, byte for byte, for a node that publishes an XML lane.
/// A wording change here is a change to every project's instruction files,
/// so it must be a deliberate edit of a golden and never a quiet one.
#[test]
fn the_router_body_is_pinned_byte_for_byte() {
    let body = render_router(&facts(
        "org.vibevm.core/vibevm",
        Some("0123456789ab"),
        SpecFormat::Xml,
    ));
    assert_eq!(
        body,
        "<!-- Generated by vibe — do not edit inside this block; it is rewritten on `vibe install`. Text outside the <vibevm> markers is yours. -->

# Session boot — project org.vibevm.core/vibevm

This block applies only when the directory holding this file is the root of
your session's project. If you found this file in a sub-directory or in a
materialised dependency copy, ignore this block. A task carrying the subagent
quiet clause ignores it as well: its packet names the files it reads.

The boot lane is `vibevm/vibespecs/boot/STATIC.xml`, then every file listed in `vibevm/vibespecs/boot/INDEX.md`. Parts of it may already be in your context, at
any position. A delivered file sits between two lines:

    vibe:lane-begin org.vibevm.core/vibevm <path> <id>
    vibe:lane-end org.vibevm.core/vibevm <path> <id>

1. A file with both lines in your context is read. Do not read it again. If
   the same pair appears twice the copies are identical; follow one.
2. A file with a begin line and no end line was cut short. Read it from disk.
3. The expected id of `vibevm/vibespecs/boot/STATIC.xml` is `0123456789ab`. If its lane lines
   carry another id the delivered copy is out of date: read the whole
   lane from disk.
4. A lane file with no lane lines in your context, and which you have
   not already read in this session: read it from disk — `vibevm/vibespecs/boot/STATIC.xml`
   first, then INDEX order.
5. An INDEX row carrying a `when` condition is read only when that condition
   holds for this session.

The boot order — this file, `vibevm/vibespecs/boot/STATIC.xml`, the INDEX files — is an order of
precedence, not of position. A lane delivered before this file has been read.

Boot is pure file-reading — there is nothing to execute."
    );
}

/// Four properties the owner's decisions put on the text, asserted
/// mechanically rather than by reading: no `@` (so no harness treats a line
/// as an import), no positional word (which breaks silently once the lane
/// arrives first), the scope sentence, and the quiet-clause sentence.
#[test]
fn the_router_carries_no_import_line_and_no_positional_word() {
    for spec_format in [SpecFormat::Mixed, SpecFormat::Markdown, SpecFormat::Xml] {
        for hash in [None, Some("0123456789ab")] {
            let body = render_router(&facts("org.x/y", hash, spec_format));
            assert!(!body.contains('@'), "an `@` would be a harness directive");
            for positional in ["above", "below", "you have just read", "earlier in this"] {
                assert!(
                    !body.to_ascii_lowercase().contains(positional),
                    "`{positional}` breaks silently under launch delivery: {body}"
                );
            }
            assert!(body.contains("the root of\nyour session's project"));
            assert!(body.contains("subagent\nquiet clause"));
            // Presence, not position: the test is where the markers are, and
            // the word "order" appears only about precedence.
            assert!(body.contains("order of\nprecedence") || body.contains("order of precedence"));
        }
    }
}

/// A node with no static lane gets the same five rules in the same order —
/// a different shape would make two projects' blocks incomparable — and no
/// expected id at all rather than an empty one.
#[test]
fn a_node_with_no_lane_keeps_the_rule_shape_and_states_there_is_no_id() {
    let body = render_router(&facts("org.x/y", None, SpecFormat::Xml));
    for rule in ["\n1. ", "\n2. ", "\n3. ", "\n4. ", "\n5. "] {
        assert!(body.contains(rule), "rule {rule:?} is missing: {body}");
    }
    assert!(body.contains("publishes no static lane"));
    assert!(!body.contains("STATIC.xml"), "there is no lane to name");
    assert!(!body.contains("expected id of"));
}

/// The lane the block names follows the target format, exactly as the
/// generated artifacts do (`#SYS-LANE-SPELLING`).
#[test]
fn the_named_lane_follows_the_target_format() {
    let xml = render_router(&facts("org.x/y", Some("aaaaaaaaaaaa"), SpecFormat::Xml));
    assert!(xml.contains("vibevm/vibespecs/boot/STATIC.xml"));
    assert!(!xml.contains("STATIC.md"));
    let md = render_router(&facts(
        "org.x/y",
        Some("aaaaaaaaaaaa"),
        SpecFormat::Markdown,
    ));
    assert!(md.contains("vibevm/vibespecs/boot/STATIC.md"));
    assert!(!md.contains("STATIC.xml"));
}

/// The expected id follows the lane and nothing else, which is what keeps
/// an edit of `90-user.xml` from rewriting three tracked files
/// (`#SYS-LANE-MARKERS`).
#[test]
fn the_expected_id_follows_the_lane_alone() {
    let one = render_router(&facts("org.x/y", Some("0123456789ab"), SpecFormat::Xml));
    let two = render_router(&facts("org.x/y", Some("ba9876543210"), SpecFormat::Xml));
    assert_ne!(one, two);
    assert_eq!(
        one.replace("0123456789ab", "ba9876543210"),
        two,
        "the id is the only difference between two lanes' blocks"
    );
}

/// The node id is the manifest's own consumer coordinate, falling back to
/// the workspace's and then to the reserved spelling — one function, because
/// the writer and the prefix's witness must agree to the byte.
#[test]
fn the_node_id_is_the_declared_coordinate_then_the_host_then_reserved() {
    let project: Manifest =
        toml::from_str("[project]\nname = \"demo\"\nversion = \"0.0.1\"\n").unwrap();
    let grouped: Manifest =
        toml::from_str("[project]\nname = \"demo\"\ngroup = \"org.x\"\nversion = \"0.0.1\"\n")
            .unwrap();
    let host = SelfCoordinate::new(Some("org.vibevm.core".into()), "vibevm".into());
    let nameless = SelfCoordinate::new(None, String::new());
    assert_eq!(router_node_id(Some(&project), &host), "demo");
    assert_eq!(router_node_id(Some(&grouped), &host), "org.x/demo");
    assert_eq!(router_node_id(None, &host), "org.vibevm.core/vibevm");
    assert_eq!(router_node_id(None, &nameless), UNDECLARED_NODE_ID);
}

/// A materialised dependency copy's block says it does not apply, and says
/// nothing a harness could read as this project's boot rules.
#[test]
fn a_neutralised_block_states_that_it_does_not_apply() {
    let block = render_neutralised_block();
    assert!(block.starts_with("<vibevm>\n"));
    assert!(block.ends_with("</vibevm>\n"));
    assert!(block.contains("Not this session's boot"));
    assert!(!block.contains('@'));
    assert!(!block.contains("vibe:lane-begin"));
    assert!(
        !block.contains("INDEX.md"),
        "a neutralised block names no boot file"
    );
}

/// Codex's silent truncation, classified once and read twice — the writer
/// refuses the past-the-limit case and `vibe check` warns on the near one.
#[test]
fn the_codex_budget_has_three_verdicts_with_one_measurement() {
    assert_eq!(CodexBudget::of(1_000), CodexBudget::Fits);
    assert_eq!(
        CodexBudget::of(PROJECT_DOC_MAX_BYTES - PROJECT_DOC_WARN_MARGIN),
        CodexBudget::Fits,
        "exactly the margin away is still inside it"
    );
    assert_eq!(
        CodexBudget::of(PROJECT_DOC_MAX_BYTES - PROJECT_DOC_WARN_MARGIN + 1),
        CodexBudget::Near {
            end: PROJECT_DOC_MAX_BYTES - PROJECT_DOC_WARN_MARGIN + 1
        }
    );
    assert_eq!(
        CodexBudget::of(PROJECT_DOC_MAX_BYTES),
        CodexBudget::Near {
            end: PROJECT_DOC_MAX_BYTES
        },
        "the limit itself is the last offset that survives"
    );
    assert_eq!(
        CodexBudget::of(PROJECT_DOC_MAX_BYTES + 1),
        CodexBudget::Truncated {
            end: PROJECT_DOC_MAX_BYTES + 1
        }
    );
    assert!(CodexBudget::Fits.message("AGENTS.md").is_none());
    let near = CodexBudget::of(PROJECT_DOC_MAX_BYTES)
        .message("AGENTS.md")
        .expect("the near case has a message");
    assert!(near.contains("AGENTS.md") && near.contains("32768") && near.contains("within 4 KB"));
    let over = CodexBudget::of(PROJECT_DOC_MAX_BYTES + 1)
        .message("AGENTS.md")
        .expect("the truncated case has a message");
    assert!(over.contains("is told nothing"));
}

/// This repository's own block, measured: the whole point of D11's refusal
/// is that the real entrypoint has headroom, and a regression that doubles
/// the block's size should fail here rather than in a Codex session.
#[test]
fn the_rendered_block_is_small_against_the_instruction_file_budget() {
    let block = render_block(&facts(
        "org.vibevm.core/vibevm",
        Some("0123456789ab"),
        SpecFormat::Xml,
    ));
    println!("router block: {} bytes", block.len());
    assert!(
        block.len() < 4 * 1024,
        "the block itself must leave an entrypoint most of its 32 KiB: {} bytes",
        block.len()
    );
}

/// The facts carry nothing volatile: the same declared inputs render the
/// same bytes, and a declared OS is not in the block at all.
#[test]
fn the_body_is_a_pure_function_of_its_declared_facts() {
    let once = render_router(&facts("org.x/y", Some("0123456789ab"), SpecFormat::Xml));
    let twice = render_router(&facts("org.x/y", Some("0123456789ab"), SpecFormat::Xml));
    assert_eq!(once, twice);
    for os in [TargetOs::Linux, TargetOs::Macos, TargetOs::Windows] {
        assert!(
            !once.contains(os.as_str()),
            "a host OS name has no place in a tracked file"
        );
    }
}
