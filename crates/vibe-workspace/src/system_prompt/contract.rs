//! The transport contract — the one piece of generated prose in the prefix.
//!
//! It sits at the entrypoint's managed-block byte range and states, as plain
//! facts about the request: which sources this layer has supplied, each by
//! role and relative path; that their content is present and need not be
//! read again *to discharge the boot obligations they themselves state*; and
//! that every boot file it does not name has **not** been supplied and must
//! not be treated as read (PROP-076 `#SYS-TRANSPORT-CONTRACT`).
//!
//! Four things it deliberately does not do. It does not forbid tool calls in
//! general — a later instruction to check a file's current state on disk
//! stays valid, and no text can guarantee an agent makes no tool call. It
//! does not instruct the agent to run `vibe` or anything else: PROP-009
//! `#PURE-FILE-READING` and `#REJ-RUN-VIBE` forbid turning boot into a
//! command, and `vibe prompt prepare` is the calling program's preflight,
//! never the model's errand. It carries no digest, build time, checkout path
//! or counter, so it can never be the thing that makes two otherwise equal
//! prefixes differ. And it speaks only for its own layer, which is what lets
//! PROP-074's composer append each layer's contract instead of regenerating
//! one global one (`#SYS-LAYER-CONCATENATION`).
//!
//! The text is pinned behind a **recipe number**. A wording change moves
//! every prefix digest in the world, so it is a new recipe and a new entry in
//! `campaigns/sys-prompt-2026-11/FORMAT-CHANGES.md` (`SP-FMT-009`), never a
//! prose edit. It also carries no positional word — "above", "below", "you
//! have just read" — because a conforming delivery may place the lane first
//! (`#SYS-BOOT-ORDER-IS-PRECEDENCE`).

specmark::scope!("spec://org.vibevm.core/vibevm/common/PROP-076#SYS-TRANSPORT-CONTRACT");

use crate::{WorkspaceError, layout_paths};

use super::{InputRole, compose_error};

/// The recipe this version generates when `[system_prompt] recipe` is absent.
pub const CURRENT_RECIPE: u32 = 1;

/// Every recipe this build can render. A pinned recipe outside the set is a
/// refusal, not a silent fall-back to the current one: a pin that quietly
/// did nothing would be worse than no pin.
pub const KNOWN_RECIPES: &[u32] = &[1];

/// One source this layer supplies, as the contract names it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SuppliedSource<'a> {
    /// The role, which is what the reader needs to know the text's standing.
    pub role: InputRole,
    /// The source's path relative to the selected node, forward-slashed.
    /// Relative on purpose: an absolute checkout path would make the prefix
    /// differ by machine (`#SYS-NO-VOLATILE`).
    pub relative: &'a str,
}

/// How the contract names each role. Spelled here rather than reusing
/// [`InputRole::as_str`] because this is prose a model reads, and the
/// sidecar's machine spelling must stay free to change without moving a
/// prefix digest.
fn role_label(role: InputRole) -> &'static str {
    match role {
        InputRole::Template => "project frame",
        InputRole::Entrypoint => "project entrypoint",
        InputRole::Lane => "compiled static boot lane",
    }
}

/// Render the contract for one recipe.
///
/// ```
/// use vibe_workspace::system_prompt::{InputRole, SuppliedSource, render_contract};
///
/// let text = render_contract(
///     1,
///     &[SuppliedSource { role: InputRole::Entrypoint, relative: "AGENTS.md" }],
/// )?;
/// assert!(text.starts_with("<!-- Generated by vibe"));
/// assert!(text.contains("project entrypoint — AGENTS.md"));
/// // Nothing volatile, and nothing a harness would read as an import.
/// assert!(!text.lines().any(|line| line.trim_start().starts_with('@')));
/// # Ok::<(), vibe_workspace::WorkspaceError>(())
/// ```
pub fn render_contract(
    recipe: u32,
    supplied: &[SuppliedSource<'_>],
) -> Result<String, WorkspaceError> {
    if !KNOWN_RECIPES.contains(&recipe) {
        return Err(compose_error(
            "transport contract",
            format!(
                "`[system_prompt] recipe = {recipe}` is not a recipe this build can render \
                 (known: {known}) — omit the key to take the current recipe {CURRENT_RECIPE}",
                known = KNOWN_RECIPES
                    .iter()
                    .map(u32::to_string)
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
        ));
    }
    Ok(render_recipe_1(supplied))
}

/// Recipe 1 — the initial text. Every byte of it is pinned by a golden test.
fn render_recipe_1(supplied: &[SuppliedSource<'_>]) -> String {
    let index = layout_paths::boot(vibe_core::layout::INDEX_MD);
    let mut out = String::with_capacity(900);
    out.push_str(
        "<!-- Generated by vibe — the PROP-076 transport contract, recipe 1. \
         Do not edit; it is rewritten on `vibe install`. -->\n\n\
         # What this request already supplies\n\n",
    );
    if supplied.is_empty() {
        out.push_str(
            "This layer supplies no boot source as text. Every boot file this project \
             names must be treated as unread.\n\n",
        );
    } else {
        out.push_str(
            "The project layer of this request carries these boot sources as text, \
             in full:\n\n",
        );
        for source in supplied {
            out.push_str("- ");
            out.push_str(role_label(source.role));
            out.push_str(" — ");
            out.push_str(source.relative);
            out.push('\n');
        }
        out.push_str(
            "\nReading them again is not needed to discharge the boot obligations they \
             themselves state. Nothing further is claimed: an obligation this project \
             states beyond reading a file — resolving a user-local context, reading a \
             plan, consulting a campaign document — is not discharged by transport, and \
             transport does not report it as discharged.\n\n",
        );
    }
    out.push_str("Every other boot file is not supplied by this layer. Each entry of ");
    out.push_str(&index);
    out.push_str(
        ", and every file absent from the list, must be treated as unread unless another \
         part of this request states that it was supplied.\n\n\
         This notice speaks only for the project layer of this request.\n",
    );
    out
}

