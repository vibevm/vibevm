//! Publication: from a node's computed generation to the bytes the boot
//! transaction commits — and to the removal when the node has opted out.
//!
//! This cell composes and decides; it writes nothing. Everything it produces
//! goes into the one existing publication transaction as four more roles, so
//! there is no second atomicity story and no window in which a new prefix is
//! paired with a sidecar of another generation
//! (`#SYS-TRANSACTION-ROLES`).
//!
//! **Three artifacts and an ignore file, together or not at all.** The
//! prefix, its sidecar and the agent lane are a coherent set: they are
//! derived from one generation's inputs, they are removed together, and they
//! are covered by one `.gitignore` that `vibe` writes into the boot
//! directory it already owns — never the repository root's, which is the
//! developer's file (`#SYS-ARTIFACTS-NOT-TRACKED`). The ignore file is part
//! of the same commit because an artifact that exists before its ignore line
//! is an artifact a `git add -A` commits.
//!
//! **Opting out is deleting the template**, and the next publication removes
//! exactly the four paths vibe owns in that directory. Nothing is read or
//! staged at all for a node that has neither a template nor a leftover
//! artifact, which is what keeps every project that does not want this
//! feature byte-identical to before it existed (`#SYS-OPT-IN`).

