/// The ignore file's exact bytes.
///
/// It is a constant and not a template: the paths it covers are the reserved
/// names of `PROP-076#SYS-FILES` and nothing about a project can change
/// them, so a generated-and-varying ignore file would be a changing artifact
/// with no changing input. The patterns are anchored with a leading `/` so
/// they bind in this directory only, and the file ignores **itself** —
/// otherwise vibe would create an untracked file of its own in every opted-in
/// project's `git status`.
///
/// It says *why* in the same breath as *what*, because a reader who finds
/// this file is exactly the reader about to ask why `STATIC.*` and
/// `INDEX.md`, two generated files in the very same directory, keep the
/// opposite rule.
pub const BOOT_IGNORE_BODY: &str = "\
# Generated by vibe — do not edit.
#
# The system-prompt artifacts below are generated, never committed: each is a
# deterministic function of committed inputs (the authored
# `SYSTEM-TEMPLATE.md`, the selected entrypoint, the compiled static lane and
# `[system_prompt]`), so a committed copy would carry no fact its inputs do
# not — and could be stale and then believed. `vibe prompt build` reproduces
# them; `vibe check` reports it as an error when git tracks one.
#
# The boot lane in this same directory keeps the opposite rule for the
# opposite reason: `STATIC.*` and `INDEX.md` are read by a session whose only
# tool is a file reader, so they must survive a fresh clone. Every consumer
# of a prefix is a program that is already invoking `vibe`.
#
# Only this directory is ignored. The repository root `.gitignore` is the
# developer's file and vibe never touches it.
/.gitignore
/SYSTEM.md
/SYSTEM.meta.json
/AGENT-LANE.md
";

/// Observes one band-U body for the agent lane.
///
/// A separate seam from [`PrefixReader`] because the spelling is different:
/// a continuation row's path is **workspace-root-relative**, which is the
/// only spelling in which a dependency slot's boot file can be named at all.
/// Like the prefix reader it exists so that `#SYS-NO-HOME-EXPANSION` is
/// provable by counting reads rather than by inspecting output — an
/// implementation of one's own is how a caller observes somewhere else, and
/// how a test counts what was opened:
///
/// ```
/// use std::cell::RefCell;
/// use vibe_workspace::WorkspaceError;
/// use vibe_workspace::system_prompt::LaneBodyReader;
///
/// struct Counting(RefCell<Vec<String>>);
///
/// impl LaneBodyReader for Counting {
///     fn read_root(&self, relative: &str) -> Result<Option<Vec<u8>>, WorkspaceError> {
///         self.0.borrow_mut().push(relative.to_string());
///         // Absence is an answer here too — the caller decides what it means.
///         Ok((relative == "vibevm/vibespecs/boot/90-user.xml").then(|| b"# mine\n".to_vec()))
///     }
/// }
///
/// let reader = Counting(RefCell::new(Vec::new()));
/// assert_eq!(
///     reader.read_root("vibevm/vibespecs/boot/90-user.xml")?,
///     Some(b"# mine\n".to_vec())
/// );
/// assert_eq!(reader.read_root("vibevm/vibedeps/org.x/1.0.0/boot/main.md")?, None);
/// assert_eq!(reader.0.into_inner().len(), 2);
/// # Ok::<(), WorkspaceError>(())
/// ```
pub trait LaneBodyReader {
    /// The bytes at `relative` (workspace-root-relative, forward-slashed),
    /// or `None` when the file is absent.
    fn read_root(&self, relative: &str) -> Result<Option<Vec<u8>>, WorkspaceError>;
}

/// What this generation publishes for one node's system prompt.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum PromptPublication {
    /// Nothing at all: no template, and no leftover artifact to retire. The
    /// journal carries no prompt member and no prompt path is opened.
    Untouched,
    /// The node has opted out and at least one artifact is still on disk:
    /// the four paths end absent, inside this same commit.
    Removed,
    /// The node has opted in: these bytes, as one coherent set.
    Published(Box<PublishedPrompt>),
}

/// The bytes of one opted-in generation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct PublishedPrompt {
    /// `SYSTEM.md` — band P.
    pub(crate) system: Vec<u8>,
    /// `SYSTEM.meta.json` — the witness of `#SYS-SIDECAR`.
    pub(crate) meta: Vec<u8>,
    /// `AGENT-LANE.md` — the lane part of band P plus the whole of band U.
    pub(crate) lane: Vec<u8>,
}

/// One node's generation, as the two publication seams hold it.
pub(crate) struct PromptPublishRequest<'a> {
    /// The node's canonical workspace-relative path (`.` for the root).
    pub(crate) node_rel: &'a str,
    /// The node's absolute directory.
    pub(crate) node_dir: &'a Path,
    /// The node's own manifest — the authority for `[system_prompt]`.
    pub(crate) manifest: &'a Manifest,
    /// The target format this generation publishes the lane under.
    pub(crate) spec_format: SpecFormat,
    /// The node's computed effective boot.
    pub(crate) effective: &'a EffectiveBoot,
    /// The compiled lane bytes this generation publishes, or `None`.
    pub(crate) lane: Option<&'a [u8]>,
    /// The `INDEX.md` bytes this generation publishes, whose digest fixes
    /// the continuation plan's identity.
    pub(crate) index_bytes: &'a [u8],
    /// The router facts the managed-block write of this same generation
    /// uses, so the entrypoint witness is the bytes the write will leave.
    pub(crate) router: RouterFacts,
}

/// Decide and compose one node's prompt publication.
pub(crate) fn prepare_publication(
    request: &PromptPublishRequest<'_>,
    reader: &dyn PrefixReader,
    bodies: &dyn LaneBodyReader,
) -> Result<PromptPublication, WorkspaceError> {
    let captured = capture_prefix_inputs(
        PrefixCapture {
            node_rel: request.node_rel,
            node_dir: request.node_dir,
            manifest: request.manifest,
            spec_format: request.spec_format,
            effective: request.effective,
            lane: request.lane,
            router: request.router.clone(),
        },
        reader,
    )?;
    let Some(captured) = captured else {
        return Ok(if any_artifact_present(request.node_dir)? {
            PromptPublication::Removed
        } else {
            PromptPublication::Untouched
        });
    };
    compose_all(request, &captured, bodies)
        .map(|published| PromptPublication::Published(Box::new(published)))
}

/// Whether the boot directory still holds anything this feature owns.
///
/// Asked only once the template is known absent, and it is the whole of
/// "exactly the outputs it can prove it owns": a path vibe does not own is
/// never consulted, and a directory holding none of the four is left
/// completely alone (`#SYS-REMOVAL-AND-CONFLICT`).
fn any_artifact_present(node_dir: &Path) -> Result<bool, WorkspaceError> {
    for name in owned_names() {
        let path = node_dir.join(layout::current_boot_dir()).join(name);
        crate::safe_file::preflight_absent_or_regular(&path)
            .map_err(|error| refusal(path.clone(), error.to_string()))?;
        if crate::safe_file::read_optional(&path)
            .map_err(|error| refusal(path.clone(), error.to_string()))?
            .is_some()
        {
            return Ok(true);
        }
    }
    Ok(false)
}

/// The four names in the boot directory this feature owns, ignore file
/// included. One list, because every rule here applies to all four.
fn owned_names() -> [&'static str; 4] {
    [
        layout::BOOT_GITIGNORE,
        layout::SYSTEM_MD,
        layout::SYSTEM_META_JSON,
        layout::AGENT_LANE_MD,
    ]
}

/// Compose the prefix, the sidecar and the agent lane from one witnessed
/// input set. Every fallible step happens here, before publication, so a
/// failure is a composition failure and never a half-written set.
fn compose_all(
    request: &PromptPublishRequest<'_>,
    captured: &CapturedPrefixInputs,
    bodies: &dyn LaneBodyReader,
) -> Result<PublishedPrompt, WorkspaceError> {
    let settings = PrefixSettings::of(request.manifest)?;
    let prefix = compose_prefix(captured, &settings)?;
    let sidecar = compose_sidecar(
        captured,
        &settings,
        &prefix,
        SidecarFacts {
            plan: &captured.plan,
            index_bytes: Some(request.index_bytes),
        },
    )?;
    let meta = render_sidecar_bytes(&sidecar)?;
    let lane = compose_lane(request, captured, &settings, bodies)?;
    Ok(PublishedPrompt {
        system: prefix.bytes,
        meta,
        lane: lane.bytes,
    })
}

/// The agent lane: `STATIC.*` then band U, in plan order.
///
/// The band-U bodies are read **here**, through the boot plan's own
/// workspace-root-relative spellings, because the composer is pure and the
/// bytes are the caller's — `vibe agent` recomposes the same artifact at
/// every launch from the files then on disk (`#SYS-AGENT-LANE`). A row whose
/// file is absent is a refusal naming it: the plan said a session reads that
/// file, and silently delivering a lane short of it would be the quiet
/// failure this campaign exists to avoid.
fn compose_lane(
    request: &PromptPublishRequest<'_>,
    captured: &CapturedPrefixInputs,
    settings: &PrefixSettings,
    bodies: &dyn LaneBodyReader,
) -> Result<super::ComposedLane, WorkspaceError> {
    let mut paths: Vec<String> = Vec::new();
    let mut owned: Vec<Vec<u8>> = Vec::new();
    if let Some(lane) = &captured.lane {
        paths.push(project_relative(request.node_rel, &lane.input.relative));
        owned.push(lane.input.bytes.clone());
    }
    for row in captured.plan.resolve_host(settings.host).unconditional() {
        let bytes = bodies.read_root(&row.path)?.ok_or_else(|| {
            refusal(
                request.node_dir.join(&row.path),
                format!(
                    "the boot plan names `{}` as an unconditional continuation entry, but the \
                     file is absent, so the agent lane cannot deliver it",
                    row.path
                ),
            )
        })?;
        paths.push(row.path.clone());
        owned.push(bytes);
    }
    let sources: Vec<LaneSource<'_>> = paths
        .iter()
        .zip(owned.iter())
        .map(|(path, bytes)| LaneSource {
            path: path.as_str(),
            bytes: bytes.as_slice(),
        })
        .collect();
    compose_agent_lane(&settings.node_id, &sources)
}

/// A node-relative path, re-based to the workspace root — the spelling the
/// continuation rows already use, so the lane's marker paths are one
/// vocabulary rather than two.
fn project_relative(node_rel: &str, relative: &str) -> String {
    if node_rel == "." {
        relative.to_owned()
    } else {
        format!("{node_rel}/{relative}")
    }
}

/// The production band-U reader: the held workspace's root node.
pub(crate) fn bound_lane_reader(
    sources: &crate::boot_artifacts::declared_sources::DeclaredBootSources,
) -> impl LaneBodyReader + '_ {
    BoundLaneReader { sources }
}

struct BoundLaneReader<'a> {
    sources: &'a crate::boot_artifacts::declared_sources::DeclaredBootSources,
}

impl LaneBodyReader for BoundLaneReader<'_> {
    fn read_root(&self, relative: &str) -> Result<Option<Vec<u8>>, WorkspaceError> {
        self.sources.root_input(relative)
    }
}

fn refusal(path: std::path::PathBuf, reason: String) -> WorkspaceError {
    WorkspaceError::SystemPromptCapture { path, reason }
}

