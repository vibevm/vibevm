//! Harness-neutral built-in agent types and their Claude Code projection.
//!
//! A type names its input without reading it: full-context workers carry the
//! composed project lane, while packet executors carry installed executor
//! rules alone. Rendering preserves the supplied body's bytes; ownership is
//! identified by a marker immediately following the frontmatter.

specmark::scope!("spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES");

/// Claude Code's project-local directory for agent type files.
#[specmark::spec(documents = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub const CLAUDE_AGENT_TYPES_DIR: &str = ".claude/agents";

/// Namespace reserved for generated agent type names.
#[specmark::spec(documents = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub const AGENT_TYPE_PREFIX: &str = "vibe-";

/// Ownership marker, placed as the first body line after the frontmatter.
#[specmark::spec(documents = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub const GENERATED_MARKER: &str = "<!-- Generated by vibe; do not edit. vibe rewrites this file at every vibe agent claude launch and on vibe prompt types. -->";

/// Full-context worker instructions, without a trailing newline.
#[specmark::spec(documents = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub const WORKER_PREFACE: &str = "You are a full-context worker started by a lead session in this project. The project's composed boot lane follows. It is already in your context, so do not read its files from disk again. Do the task the lead gives you and report back to the lead.";

/// Directory-local ignore file for reproducible generated agent types.
#[specmark::spec(documents = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub const AGENT_TYPES_IGNORE_BODY: &str = "\
# Generated by vibe — do not edit.
#
# The vibe-*.md subagent types in this directory are generated from this
# project's composed boot lane and installed rules, at every `vibe agent
# claude` launch and by `vibe prompt types`, so they are never committed.
# Only this directory is affected; the repository root `.gitignore` is the
# developer's file and vibe never touches it.
/.gitignore
/vibe-*.md
";

/// First line identifying the generated directory-local ignore file.
#[specmark::spec(documents = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub const AGENT_TYPES_IGNORE_FIRST_LINE: &str = "# Generated by vibe — do not edit.";

/// Input to resolve before rendering an agent type, independent of any harness.
#[derive(Debug, Clone, PartialEq, Eq)]
#[specmark::spec(documents = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub enum AgentTypeBody {
    /// This project's composed boot lane.
    ProjectLane,
    /// One file from an installed package, separate from the project lane.
    PackageFile {
        /// Package group identity.
        group: String,
        /// Package name within the group.
        name: String,
        /// Package-relative path to the body.
        path: String,
    },
}

/// Portable description of an agent type and the source of its body.
#[derive(Debug, Clone, PartialEq, Eq)]
#[specmark::spec(documents = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub struct AgentTypeSpec {
    /// Unprefixed type name.
    pub name: String,
    /// Description advertised to the lead session.
    pub description: String,
    /// Optional instructions inserted before the resolved body.
    pub preface: Option<String>,
    /// Source to resolve without importing executor rules into the project lane.
    pub body: AgentTypeBody,
}

impl AgentTypeSpec {
    /// The generated type name, in the reserved namespace.
    #[specmark::spec(implements = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
    pub fn type_name(&self) -> String {
        format!("{AGENT_TYPE_PREFIX}{}", self.name)
    }

    /// Claude Code's project-relative file path, always forward-slashed.
    #[specmark::spec(implements = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
    pub fn file(&self) -> String {
        format!("{CLAUDE_AGENT_TYPES_DIR}/{}.md", self.type_name())
    }
}

/// Built-in types in stable order: full-context worker, then packet executor.
#[specmark::spec(implements = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub fn builtin_agent_types() -> Vec<AgentTypeSpec> {
    vec![
        AgentTypeSpec {
            name: "worker".to_owned(),
            description: "Use for any worker that needs this project's full context (its rules, specs and boot lane), such as research, review or design without a task packet. Workers of this type share one cached system prompt.".to_owned(),
            preface: Some(WORKER_PREFACE.to_owned()),
            body: AgentTypeBody::ProjectLane,
        },
        AgentTypeSpec {
            name: "executor".to_owned(),
            description: "Use for every executor given one task packet. It follows the packet and the executor rules only, without the project boot lane; the packet must carry the subagent quiet clause.".to_owned(),
            preface: None,
            body: AgentTypeBody::PackageFile {
                group: "org.vibevm.world".to_owned(),
                name: "working-rules".to_owned(),
                path: "rules/worker.md".to_owned(),
            },
        },
    ]
}

/// Render frontmatter, ownership marker, optional preface, and body in order.
///
/// The supplied body is opaque: no newline is added or stripped, and even
/// non-UTF-8 bytes are preserved.
///
/// ```
/// use vibe_workspace::system_prompt::agent_types::{
///     builtin_agent_types, render_claude_agent_type,
/// };
///
/// let executor = &builtin_agent_types()[1];
/// let rendered = render_claude_agent_type(executor, b"RULES\r\n\xff");
/// assert!(rendered.starts_with(b"---\nname: vibe-executor\n"));
/// assert!(rendered.ends_with(b"\n\nRULES\r\n\xff"));
/// let empty = render_claude_agent_type(executor, b"");
/// assert_eq!(&rendered[empty.len()..], b"RULES\r\n\xff");
/// ```
#[specmark::spec(implements = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub fn render_claude_agent_type(spec: &AgentTypeSpec, body: &[u8]) -> Vec<u8> {
    let mut rendered = format!(
        "---\nname: {}\ndescription: {}\n---\n{GENERATED_MARKER}\n\n",
        spec.type_name(),
        spec.description,
    )
    .into_bytes();
    if let Some(preface) = &spec.preface {
        rendered.extend_from_slice(preface.as_bytes());
        rendered.extend_from_slice(b"\n\n");
    }
    rendered.extend_from_slice(body);
    rendered
}

/// Recognize generated ownership only immediately after valid frontmatter.
///
/// Lines split on LF and lose at most one trailing CR. The first line must
/// be `---`; the first later `---` must be immediately followed by the exact
/// marker. Invalid UTF-8 in any inspected line is rejected, but body bytes
/// beyond the marker are not inspected. This is ownership detection, not YAML
/// validation.
///
/// ```
/// use vibe_workspace::system_prompt::agent_types::{
///     builtin_agent_types, is_generated_agent_type, render_claude_agent_type,
/// };
///
/// let rendered = render_claude_agent_type(&builtin_agent_types()[0], b"\xff");
/// assert!(is_generated_agent_type(&rendered));
/// assert!(!is_generated_agent_type(b"---\nname: custom\n---\nAuthored body\n"));
/// assert!(!is_generated_agent_type(b""));
/// assert!(!is_generated_agent_type(b"---\n\xff\n---\n"));
/// ```
#[specmark::spec(implements = "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-WORKER-TYPES")]
pub fn is_generated_agent_type(bytes: &[u8]) -> bool {
    let mut lines = bytes
        .split(|byte| *byte == b'\n')
        .map(|line| std::str::from_utf8(line.strip_suffix(b"\r").unwrap_or(line)).ok());
    if lines.next() != Some(Some("---")) {
        return false;
    }
    while let Some(line) = lines.next() {
        match line {
            Some("---") => return lines.next() == Some(Some(GENERATED_MARKER)),
            None => return false,
            _ => {}
        }
    }
    false
}

