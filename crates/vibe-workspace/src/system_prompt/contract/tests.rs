//! The transport contract, pinned byte for byte.
//!
//! The text is prose, and prose drifts. A wording change moves every prefix
//! digest in the world, so recipe 1 gets a golden assertion over its exact
//! bytes: a later edit either comes with a new recipe number or fails here
//! (`#SYS-TRANSPORT-CONTRACT`, `SP-FMT-009`).
specmark::scope!(
    "spec://org.vibevm.core/vibevm/common/PROP-076#SYS-TRANSPORT-CONTRACT",
    r = 1
);

use super::*;

fn all_three() -> Vec<SuppliedSource<'static>> {
    vec![
        SuppliedSource {
            role: InputRole::Template,
            relative: "vibevm/vibespecs/boot/SYSTEM-TEMPLATE.md",
        },
        SuppliedSource {
            role: InputRole::Entrypoint,
            relative: "AGENTS.md",
        },
        SuppliedSource {
            role: InputRole::Lane,
            relative: "vibevm/vibespecs/boot/STATIC.xml",
        },
    ]
}

#[test]
fn recipe_1_is_pinned_byte_for_byte() {
    let text = render_contract(1, &all_three()).expect("recipe 1 renders");
    assert_eq!(
        text,
        "<!-- Generated by vibe — the PROP-076 transport contract, recipe 1. Do not edit; \
it is rewritten on `vibe install`. -->\n\
\n\
# What this request already supplies\n\
\n\
The project layer of this request carries these boot sources as text, in full:\n\
\n\
- project frame — vibevm/vibespecs/boot/SYSTEM-TEMPLATE.md\n\
- project entrypoint — AGENTS.md\n\
- compiled static boot lane — vibevm/vibespecs/boot/STATIC.xml\n\
\n\
Reading them again is not needed to discharge the boot obligations they themselves \
state. Nothing further is claimed: an obligation this project states beyond reading a \
file — resolving a user-local context, reading a plan, consulting a campaign document — \
is not discharged by transport, and transport does not report it as discharged.\n\
\n\
Every other boot file is not supplied by this layer. Each entry of \
vibevm/vibespecs/boot/INDEX.md, and every file absent from the list, must be treated as \
unread unless another part of this request states that it was supplied.\n\
\n\
This notice speaks only for the project layer of this request.\n"
    );
}

/// The four things the contract must not do, as four mechanical checks over
/// its own bytes.
#[test]
fn the_contract_carries_nothing_volatile_and_commands_nothing() {
    let text = render_contract(CURRENT_RECIPE, &all_three()).expect("renders");
    for forbidden in [
        "vibe prompt", // never asks the model to run anything
        "sha256",      // no digest
        "/home/",      // no absolute path
        "/fast/",
        "HEAD",
    ] {
        assert!(
            !text.contains(forbidden),
            "the contract must not carry `{forbidden}`"
        );
    }
    // No positional word: a conforming delivery may place the lane first
    // (`#SYS-BOOT-ORDER-IS-PRECEDENCE`).
    for positional in ["above", "below", "you have just read"] {
        assert!(
            !text.contains(positional),
            "the contract must not say `{positional}`"
        );
    }
    // Nothing a harness would read as an import directive.
    assert!(!text.lines().any(|line| line.trim_start().starts_with('@')));
    // It does not forbid tool calls in general.
    assert!(!text.contains("do not use"));
    assert!(!text.contains("must not read"));
}

#[test]
fn a_recipe_this_build_cannot_render_refuses_and_names_the_known_ones() {
    let error = render_contract(7, &all_three()).expect_err("an unknown recipe refuses");
    let message = error.to_string();
    assert!(message.contains("recipe = 7"), "{message}");
    assert!(message.contains("known: 1"), "{message}");
    assert!(message.contains("current recipe 1"), "{message}");
}

/// A layer that supplies nothing still says so — the honest answer, and the
/// one a composer with `entrypoint = false` and no lane produces.
#[test]
fn an_empty_supply_list_still_accounts_for_itself() {
    let text = render_contract(CURRENT_RECIPE, &[]).expect("renders");
    assert!(text.contains("This layer supplies no boot source as text."));
    assert!(text.contains("must be treated as unread"));
}

/// The contract names relative paths and only relative paths, which is why
/// it is a pure function of declared inputs.
#[test]
fn the_source_list_follows_the_supplied_roles_in_order() {
    let text = render_contract(
        CURRENT_RECIPE,
        &[SuppliedSource {
            role: InputRole::Lane,
            relative: "vibevm/vibespecs/boot/STATIC.md",
        }],
    )
    .expect("renders");
    assert!(text.contains("- compiled static boot lane — vibevm/vibespecs/boot/STATIC.md\n"));
    assert!(!text.contains("project frame"));
    assert!(!text.contains("project entrypoint"));
}
