//! Building a documentation package — one walk, every artefact
//! (PROP-057 `##PIPE-LIBRARY`, `##SITE-MOUNT`).
//!
//! What a build produces is the whole machine-facing surface of a
//! package: a page in the projection the caller asked for, the page
//! manifest, the four `llms` tiers, the card's images copied under
//! content names and the placeholders generated for the roles that
//! declared none. Every one of them is a fold over the SAME page set and
//! the same resolved content, because a second walk would be a second
//! answer and nothing would say which one the reader got.
//!
//! ## The layout is the site's address map, not a choice
//!
//! `##SITE-MOUNT` fixes where a page lives —
//! `<group>/<name>/<version>/<document>/` with a trailing slash, the
//! projections beside it as files — so a build writes that tree and a
//! local reader serves the same shapes from the same function. The one
//! thing a caller supplies is the BASE it will be served under: the
//! public site mounts at `/doc/`, a reader on the loopback mounts where
//! it likes, and a translation's site adds a language segment
//! (`/doc/ru/`) that belongs to the site's route table and not to any
//! package.
//!
//! ## What a build does NOT do
//!
//! It calls no clock — both instants arrive in [`manifest::Options`] — and
//! it runs no product of its own accord. `derived` text is generated by
//! [`crate::derived`] and handed in, so a build from a warmed store on a
//! machine that has never compiled anything still produces every page,
//! with the generated blocks marked as the gaps they are rather than
//! silently empty.
//!
//! What it does do is COUNT those gaps and say the number ([`gaps`]). A
//! build that leaves half its examples unfilled and reports the same
//! summary as one with every input in hand is a build whose report cannot
//! be read, and the count costs one line.

